"""Проекция F1 на боевой набор ПО СТРАТАМ, а не по среднему.

Зачем понадобилось. `sverka.judge.предсказать_метрики` берёт общие полноту и долю ложных
по всему набору и проецирует их при π = 0.241. Это верно только если набор представителен
по стратам, а выданный сэмпл именно по ним и перекошен `[§0в]`:

| страта | сэмпл | боевой набор |
|---|---|---|
| с вызовом инструмента | 21 поз / 2 отр | 34 / 134 |
| без вызова | 2 поз / 21 отр | 96 / 276 |

То есть 91% положительных сэмпла лежат в страте, где в бою лежит лишь 26% положительных.
Общая полнота сэмпла почти целиком описывает страту с вызовом — и проекция, посчитанная
из неё, описывает не тот набор, на котором пойдёт прогон. `[расчёт 01.09.2026]` Для замера 5
разница получается двукратной: 0.626 по среднему против 0.41 по стратам.

Здесь ставки берутся раздельно: страта с вызовом — из прогона по сэмплу (другого материала
для неё нет), текстовая — из прогона по размеченному корпусу, где 52 положительных против
двух в сэмпле. Затем складываются с БОЕВЫМИ размерами страт.

    python scripts/project_f1.py --с-вызовом data/judge_27b_anchors_fix.jsonl \
        --без-вызова data/judge_27b_all.jsonl
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

# Размеры страт боевого набора `[восстановлено из двух сабмитов, §0в]`
БОЕВЫЕ = {"с вызовом": {"поз": 34, "отр": 134}, "без вызова": {"поз": 96, "отр": 276}}


def читать(путь: str) -> list[dict]:
    return [json.loads(s) for s in Path(путь).read_text(encoding="utf-8").splitlines()
            if s.strip()]


def ставки(строки, *, порог: float, вызов: bool | None):
    if вызов is not None:
        строки = [z for z in строки if bool(z.get("есть_вызов")) is вызов]
    поз = [z for z in строки if z["label"] == 1]
    отр = [z for z in строки if z["label"] == 0]
    if not поз or not отр:
        return None
    return {"полнота": sum(z["score"] >= порог for z in поз) / len(поз),
            "ложных": sum(z["score"] >= порог for z in отр) / len(отр),
            "n_поз": len(поз), "n_отр": len(отр)}


def f1_по_стратам(с_вызовом, без_вызова) -> dict:
    tp = (БОЕВЫЕ["с вызовом"]["поз"] * с_вызовом["полнота"]
          + БОЕВЫЕ["без вызова"]["поз"] * без_вызова["полнота"])
    fp = (БОЕВЫЕ["с вызовом"]["отр"] * с_вызовом["ложных"]
          + БОЕВЫЕ["без вызова"]["отр"] * без_вызова["ложных"])
    всего_поз = БОЕВЫЕ["с вызовом"]["поз"] + БОЕВЫЕ["без вызова"]["поз"]
    fn = всего_поз - tp
    точность = tp / (tp + fp) if tp + fp else 0.0
    полнота = tp / всего_поз
    f1 = 2 * tp / (2 * tp + fp + fn) if tp else 0.0
    return {"TP": tp, "FP": fp, "FN": fn, "точность": точность, "полнота": полнота, "F1": f1}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--с-вызовом", required=True,
                    help="прогон, откуда брать ставки страты с вызовом (обычно сэмпл)")
    ap.add_argument("--без-вызова", required=True,
                    help="прогон, откуда брать ставки текстовой страты (размеченный корпус)")
    ap.add_argument("--пороги", nargs="*", type=float, default=[0.3, 0.5, 0.7, 0.9])
    a = ap.parse_args()

    вызов_ист, текст_ист = читать(a.с_вызовом), читать(a.без_вызова)
    print(f"страта с вызовом  ← {a.с_вызовом}")
    print(f"страта без вызова ← {a.без_вызова}")
    print(f"боевые размеры: с вызовом 34/134, без вызова 96/276 (всего 540, 130 положительных)\n")
    print(f"  {'порог':>5} {'вызов: полн/ложн':>20} {'текст: полн/ложн':>20} "
          f"{'точность':>9} {'полнота':>8} {'F1':>7}")

    лучший = None
    for порог in a.пороги:
        в = ставки(вызов_ист, порог=порог, вызов=True)
        т = ставки(текст_ист, порог=порог, вызов=False)
        if not в or not т:
            print(f"  {порог:>5}  нет данных по одной из страт")
            continue
        r = f1_по_стратам(в, т)
        print(f"  {порог:>5} {в['полнота']:>9.3f}/{в['ложных']:<10.3f} "
              f"{т['полнота']:>9.3f}/{т['ложных']:<10.3f} "
              f"{r['точность']:>9.3f} {r['полнота']:>8.3f} {r['F1']:>7.3f}")
        if лучший is None or r["F1"] > лучший[1]["F1"]:
            лучший = (порог, r)

    if лучший:
        print(f"\n  лучший порог {лучший[0]}: F1 = {лучший[1]['F1']:.3f}")
    print(f"  ориентиры: пол «всё = 1» 0.393 · baseline организаторов 0.4896 · лидер 0.4918")
    print(f"\n  ⚠ ставки страты с вызовом взяты с сэмпла, где в ней ВСЕГО ДВА отрицательных:"
          f"\n    доля ложных там измерена с точностью «0, 0.5 или 1» и переносится плохо."
          f"\n    Это главный источник неопределённости в числе выше.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
