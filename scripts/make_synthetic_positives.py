"""Синтетические положительные для текстовой страты: берём чистый ход и портим его нарочно.

Зачем это существует. `[замер 30.08.2026]` Полнота судьи в страте «ответ без вызова
инструмента» решает исход — там 96 галлюцинаций из 130 реального набора, — и меряется она
у нас на **двух** примерах выданного сэмпла. Корпус τ² здесь не помогает: все его 1291
положительных имеют вызов инструмента, то есть лежат в чужой страте. Ручная разметка
полусотни примеров — часы чтения тридцатитысячных контекстов.

Конструктивная порча решает это иначе: берётся ход из **решённой** симуляции (метка 0
надёжна, среда подтвердила успех траектории) и в ответ вносится дефект, который по рубрике
ТЗ обязан быть галлюцинацией. Метка 1 следует из устройства, а не из чьего-то суждения.

⚠️ **Чем это НЕ является.** Синтетика даёт оценку полноты СВЕРХУ: подменённое число заметить
легче, чем неверно отфильтрованную выборку или тонкий ложный отказ. Настоящая полнота будет
ниже. Поэтому синтетика — быстрый фильтр («судья вообще способен это увидеть?»), а не
эталон, и её обязательно контролировать ручной разметкой хотя бы на трёх десятках примеров.

Виды порчи выбраны по перечню категорий ТЗ, и намеренно только те, что живут в ТЕКСТЕ
ответа, — категории с вызовами инструментов у нас и так покрыты корпусом:

- `число` — выдуманное число: значение из ответа заменяется другим правдоподобным;
- `идентификатор` — выдуманный идентификатор: номер брони или рейса заменяется несуществующим;
- `обещание` — необоснованное утверждение о выполненном действии, которого в контексте нет;
- `отказ` — ложный отказ: агент отказывает, хотя контекст показывает, что действие возможно.

Каждая порча проверяется на **осмысленность**: если в ответе нечего портить нужным
способом, пример пропускается, а не портится наугад.

    python scripts/make_synthetic_positives.py --in data/text_negatives.jsonl \
        --out data/synthetic_positives.jsonl
"""

from __future__ import annotations

import argparse
import json
import random
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from sverka.judge_prompt import _нормчисло  # noqa: E402

_ЧИСЛО = re.compile(r"\b\d{2,7}(?:[.,]\d{1,2})?\b")
_ИДЕНТ = re.compile(r"\b(?=[A-Za-z]*\d)(?=\d*[A-Za-z])[A-Z0-9][A-Z0-9_\-]{4,}\b")

# Утверждения о действиях, которых агент не совершал. Формулировки нейтральные и типовые
# для поддержки — если бы они звучали нарочито, судья ловил бы стиль, а не подлог.
ОБЕЩАНИЯ_RU = [
    "Я уже отправил подтверждение на вашу электронную почту.",
    "Изменения вступят в силу в течение 15 минут.",
    "Я зарегистрировал обращение под номером {ид}, оператор свяжется с вами в течение суток.",
    "Средства вернутся на карту в течение трёх рабочих дней.",
    "Я снял с вашего счёта блокировку, повторите операцию через пару минут.",
]

ОБЕЩАНИЯ_EN = [
    "I have already sent the confirmation to your email address.",
    "The changes will take effect within 15 minutes.",
    "I have registered your request under number {ид}; an operator will contact you within a day.",
    "The funds will be returned to your card within three business days.",
    "I have removed the hold on your account, please retry the operation in a couple of minutes.",
]

ОТКАЗЫ_RU = [
    "К сожалению, я не могу выполнить это действие — потребуется обратиться в отделение лично.",
    "Такую операцию я провести не могу, она доступна только через приложение.",
    "К сожалению, у меня нет доступа к этим данным, обратитесь в службу поддержки.",
    "Эта операция недоступна для вашего тарифа, изменить его я тоже не могу.",
]


ОТКАЗЫ_EN = [
    "Unfortunately, I cannot perform this action — you will need to visit a branch in person.",
    "I am unable to carry out this operation; it is only available through the mobile app.",
    "Unfortunately, I do not have access to this data, please contact the support team.",
    "This operation is not available on your plan, and I cannot change the plan either.",
]

# Служебный маркер хода в начале ответа: `⟦ASSISTANT · ход 10⟧`. Портить его нельзя —
# `[инцидент 30.08.2026]` первая версия подменяла в нём НОМЕР ХОДА и выдавала это за
# выдуманное число. Получалась порча разметки, а не галлюцинация.
_МАРКЕР = re.compile(r"^\s*⟦[^⟧]*⟧\s*")

# Порог кириллицы, выше которого текст считается русским. Корпус τ² английский, конкурсные
# данные переведены; вставка на чужом языке распознавалась бы по смене языка, а не по
# необоснованности, и мерила бы не то.
def _язык(текст: str) -> str:
    кир = sum("а" <= c.lower() <= "я" or c in "ёЁ" for c in текст)
    лат = sum("a" <= c.lower() <= "z" for c in текст)
    return "ru" if кир > лат else "en"


def _тело(ответ: str) -> tuple[str, str]:
    """Отделить служебный маркер от содержательной части ответа."""
    m = _МАРКЕР.match(ответ)
    return (ответ[:m.end()], ответ[m.end():]) if m else ("", ответ)


def _другое_число(исходное: str, rnd: random.Random) -> str:
    """Подменить число так, чтобы подмена была заметна по смыслу, а не по форме.

    Множитель, а не случайная цифра: `1185` → `1420` выглядит как настоящая сумма, тогда как
    `1185` → `9999` выдаёт себя формой. Судья должен ловить расхождение с контекстом,
    а не неправдоподобность самого числа.
    """
    ц = исходное.replace(",", ".")
    try:
        v = float(ц)
    except ValueError:
        return исходное
    # Годы сдвигаются на единицы, а не умножаются: `[инцидент 30.08.2026]` множитель
    # превращал 2024 в 2651, и такая подмена ловится неправдоподобностью самого числа,
    # а не расхождением с контекстом. Мерили бы здравый смысл модели, а не сверку.
    if 1900 <= v <= 2100 and "." not in ц:
        return str(int(v) + rnd.choice([-3, -2, -1, 1, 2, 3]))
    коэф = rnd.choice([1.17, 1.31, 0.72, 0.84, 1.55])
    новое = v * коэф
    строка = f"{новое:.2f}".rstrip("0").rstrip(".") if "." in ц else str(int(round(новое)))
    return строка if _нормчисло(строка) != _нормчисло(исходное) else исходное


def _другой_идент(исходный: str, rnd: random.Random) -> str:
    буквы = "".join(rnd.choice("ABCDEFGHJKLMNPQRSTUVWXYZ") if c.isalpha()
                    else rnd.choice("23456789") for c in исходный)
    return буквы if буквы != исходный else исходный[::-1]


def испортить(ответ: str, контекст: str, вид: str, rnd: random.Random):
    """Вернуть (испорченный ответ, описание дефекта) или None, если портить нечего."""
    маркер, тело = _тело(ответ)
    язык = _язык(тело)
    # Короткие реплики вроде приветствия портить нечем: приписанное к ним обещание или
    # отказ выглядят абсурдно и распознаются без всякой проверки контекста.
    if len(тело.strip()) < 220 and вид in ("обещание", "отказ"):
        return None

    if вид == "число":
        # Портим только те числа, что есть в контексте: подмена значения, которое агент
        # взял из данных, — это ровно «выдуманное число» из рубрики. Число, которого
        # в контексте и не было, портить бессмысленно.
        конт = {_нормчисло(m.group()) for m in _ЧИСЛО.finditer(контекст)}
        кандидаты = [m for m in _ЧИСЛО.finditer(тело) if _нормчисло(m.group()) in конт]
        if not кандидаты:
            return None
        m = rnd.choice(кандидаты)
        новое = _другое_число(m.group(), rnd)
        if новое == m.group():
            return None
        return (маркер + тело[:m.start()] + новое + тело[m.end():],
                f"число {m.group()} подменено на {новое}; в контексте стоит {m.group()}")

    if вид == "идентификатор":
        конт_низ = контекст.lower()
        кандидаты = [m for m in _ИДЕНТ.finditer(тело) if m.group().lower() in конт_низ]
        if not кандидаты:
            return None
        m = rnd.choice(кандидаты)
        старый = m.group()
        новый = _другой_идент(старый, rnd)
        # Заменять ВСЕ вхождения. `[инцидент 30.08.2026]` подмена только первого оставляла
        # ниже по тексту исходный идентификатор, ответ начинал противоречить сам себе,
        # и подлог выдавал себя внутренней несогласованностью, а не расхождением
        # с контекстом. Судья ловил бы не то, что мы измеряем.
        сколько = тело.count(старый)
        return (маркер + тело.replace(старый, новый),
                f"идентификатор {старый} подменён на несуществующий {новый} "
                f"({сколько} вхождений)")

    if вид == "обещание":
        шаблон = rnd.choice(ОБЕЩАНИЯ_RU if язык == "ru" else ОБЕЩАНИЯ_EN)
        текст = шаблон.format(ид=_другой_идент("AB12345", rnd)) if "{ид}" in шаблон else шаблон
        if текст.split(",")[0][:24].lower() in ответ.lower():
            return None
        return (ответ.rstrip() + "\n\n" + текст,
                f"добавлено утверждение о действии, которого в контексте нет: «{текст}»")

    if вид == "отказ":
        # Ложный отказ приписывается к ответу, где агент как раз что-то сделал: тогда отказ
        # противоречит и контексту, и самому ответу. Если ответ короткий и сам похож на
        # отказ, портить нечего.
        if re.search(r"не могу|невозможно|обратитесь|cannot|unable to|do not have access",
                     тело, re.I):
            return None
        текст = rnd.choice(ОТКАЗЫ_RU if язык == "ru" else ОТКАЗЫ_EN)
        return (ответ.rstrip() + "\n\n" + текст,
                f"добавлен отказ, не обоснованный контекстом: «{текст}»")

    return None


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--in", dest="вход", default="data/text_negatives.jsonl")
    ap.add_argument("--out", dest="выход", default="data/synthetic_positives.jsonl")
    ap.add_argument("--seed", type=int, default=20260830)
    args = ap.parse_args()

    rnd = random.Random(args.seed)
    строки = [json.loads(s) for s in Path(args.вход).read_text(encoding="utf-8").splitlines() if s.strip()]
    виды = ["число", "идентификатор", "обещание", "отказ"]

    сделано, не_вышло = [], {в: 0 for в in виды}
    for i, r in enumerate(строки):
        вид = виды[i % len(виды)]
        итог = испортить(str(r["response"]), str(r["prompt"]), вид, rnd)
        if итог is None:
            не_вышло[вид] += 1
            continue
        испорченный, описание = итог
        сделано.append({
            "id": r["id"] + f"#синт-{вид}",
            "label": 1,
            "domain": r.get("domain", ""),
            "prompt": r["prompt"],
            "response": испорченный,
            "вид_порчи": вид,
            "дефект": описание,
            "исходный_id": r["id"],
        })

    Path(args.выход).write_text(
        "\n".join(json.dumps(x, ensure_ascii=False) for x in сделано) + "\n", encoding="utf-8")

    from collections import Counter
    print(f"исходных чистых ходов: {len(строки)}")
    print(f"испорчено: {len(сделано)}")
    print(f"  по видам: {dict(Counter(x['вид_порчи'] for x in сделано))}")
    print(f"  не удалось (нечего портить): {не_вышло}")
    print(f"→ {args.выход}")
    print("\n⚠️ Полнота на этом наборе — оценка СВЕРХУ. Подменённое число заметнее, чем")
    print("   неверно отфильтрованная выборка. Контролировать ручной разметкой.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
