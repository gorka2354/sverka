"""Собрать набор из 65 размеченных ходов текстовой страты в формат раннера судьи.

Зачем отдельный набор. Выданный сэмпл `valid.parquet` в текстовой страте даёт **два**
положительных примера `[§0в]` — на двух точках полнота не измеряется ничем. Материал нашёлся
в `reward_info.nl_assertions` траекторий τ²-bench: провалившиеся требования на естественном
языке с обоснованием ревьюера бенчмарка. `mine_nl_assertions.py` привязал их к ходам
по якорям, `build_markup_cards.py` собрал карточки, три независимых машинных прохода
разметили их большинством голосов `[§0е]`.

Метка здесь — вердикт большинства, а не выдумка скрипта:

- «кандидат» + majority «da» → label 1;
- «кандидат» + majority «net» → label 0 (требование провалилось не на этом ходе);
- «чистая» → label 0 всегда, это контрольная группа из решённых симуляций.

⚠️ Чего этот набор НЕ даёт. Он смещён по построению: привязка идёт по якорям — числам
и кодам броней, — поэтому механизм отбирает длинные насыщенные ходы. Доля «тяжёлых» здесь
0.765 против 0.087 в боевых данных `[§0е]`. Поэтому среднее по набору читать нельзя,
читать можно только разрез по тяжести хода, взвешивая потом по боевому профилю.

    python scripts/build_markup65.py --out data/markup65_for_judge.jsonl
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path


def загрузить_jsonl(путь: str) -> dict:
    return {z["id"]: z for z in (json.loads(s) for s in
                                 Path(путь).read_text(encoding="utf-8").splitlines() if s.strip())}


def свернуть_по_ходу(строки: list[dict]) -> tuple[list[dict], dict]:
    """Одна строка на ход агента: метка — «хотя бы одно требование нарушено».

    `[дефект найден 31.08.2026]` Майнер привязывает к ходу каждое провалившееся требование
    отдельно, и один и тот же ответ приходит в набор дважды и трижды: `airline__22::t11#nl11`
    и `#nl12` — это один текст. У двух ходов из 55 метки при этом **противоречили друг другу**:
    по одному требованию 1, по другому 0.

    Почему это не мелочь. Судья получает ход — контекст и ответ, — а не требование; про
    требование он не знает ничего. На двух строках с одним и тем же входом он обязан выдать
    один и тот же вердикт, значит при расходящихся метках одна из строк засчитывается
    ошибкой при любом его ответе. Это не измерение судьи, а измерение дублей.

    Свёртка по максимуму соответствует и постановке задачи: боевая метка отвечает на вопрос
    «есть ли в ответе галлюцинация», а не «нарушено ли конкретное требование».
    """
    по_ходу: dict[str, dict] = {}
    for z in строки:
        ход = z["id"].split("#")[0]
        было = по_ходу.get(ход)
        if было is None:
            по_ходу[ход] = {**z, "id": ход, "требований": 1,
                            "id_требований": [z["id"]]}
            continue
        было["требований"] += 1
        было["id_требований"].append(z["id"])
        было["label"] = max(было["label"], z["label"])
        было["единогласно"] = bool(было.get("единогласно")) and bool(z.get("единогласно"))
    свёрнуто = list(по_ходу.values())
    счёт = {"поз": sum(z["label"] for z in свёрнуто),
            "отр": sum(1 for z in свёрнуто if not z["label"])}
    слито = len(строки) - len(свёрнуто)
    print(f"свёртка по ходу: {len(строки)} строк → {len(свёрнуто)} ходов "
          f"(слито {слито}); метка хода = «нарушено хотя бы одно требование»")
    return свёрнуто, счёт


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--карточки", nargs="+", default=["data/markup_cards2.json"])
    ap.add_argument("--разметка", nargs="+", default=["data/markup_machine2.json"])
    ap.add_argument("--кандидаты", default="data/nl_candidates_for_judge.jsonl")
    ap.add_argument("--чистые", default="data/nl_clean_for_judge.jsonl")
    ap.add_argument("--out", default="data/markup65_for_judge.jsonl")
    ap.add_argument("--доп-источники", nargs="*", default=[],
                    help="ещё файлы со строками id/prompt/response — откуда брать тексты "
                         "для карточек новых сборок")
    ap.add_argument("--без-свёртки", action="store_true",
                    help="оставить по строке на требование, как было до 31.08.2026 вечера")
    a = ap.parse_args()

    # Несколько сборок карточек и разметок склеиваются в одну таблицу. Номер `n` уникален
    # только внутри своей сборки, поэтому ключом служит пара (файл разметки, номер).
    карточки, разметка = [], {}
    for файл_к, файл_р in zip(a.карточки, a.разметка):
        свои = json.loads(Path(файл_к).read_text(encoding="utf-8"))
        своя = json.loads(Path(файл_р).read_text(encoding="utf-8"))
        for к in свои:
            карточки.append({**к, "_разметка": файл_р})
        for n, v in своя.items():
            разметка[(файл_р, str(n))] = v
    источник = загрузить_jsonl(a.кандидаты) | загрузить_jsonl(a.чистые)
    for доп in a.доп_источники:
        источник |= загрузить_jsonl(доп)

    строки, потеряно, счёт = [], [], {"поз": 0, "отр": 0}
    for к in карточки:
        n, id_ = str(к["n"]), к["id"]
        м = разметка.get((к.get("_разметка", ""), n))
        если_нет = id_ not in источник
        if м is None or если_нет:
            потеряно.append((n, id_, "нет разметки" if м is None else "нет исходной строки"))
            continue
        # Контрольная группа размечена своим происхождением: это ходы решённых симуляций,
        # где ни одно требование не провалено. Голос модели по ним нужен был для слепого
        # контроля разметки, а меткой служить не может — иначе набор разметил бы сам себя.
        метка = 0 if к.get("вид") == "чистая" or м.get("вид") == "чистая" else int(м["majority"] == "da")
        z = источник[id_]
        строки.append({"id": id_, "prompt": z["prompt"], "response": z["response"],
                       "label": метка, "domain": z.get("domain", к.get("домен", "")),
                       "вид": м.get("вид", к.get("вид", "")),
                       "голоса": м.get("голоса", []),
                       "единогласно": len(set(м.get("голоса", []))) == 1})
        счёт["поз" if метка else "отр"] += 1

    if not a.без_свёртки:
        строки, счёт = свернуть_по_ходу(строки)

    out = Path(a.out)
    out.write_text("".join(json.dumps(z, ensure_ascii=False) + "\n" for z in строки),
                   encoding="utf-8")
    print(f"записано {len(строки)} строк в {out}: положительных {счёт['поз']}, "
          f"отрицательных {счёт['отр']}")
    единогласных = sum(z["единогласно"] for z in строки)
    print(f"единогласных вердиктов: {единогласных} из {len(строки)} "
          f"({единогласных / len(строки):.2f}) — остальные приняты большинством 2 из 3")
    if потеряно:
        print(f"⚠ не собрано {len(потеряно)}:")
        for n, id_, почему in потеряно[:10]:
            print(f"   карточка {n} ({id_}): {почему}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
