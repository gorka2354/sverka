"""Свести три прохода разметки в вердикт большинством и проверить, годится ли он.

Проверок три, и каждая способна забраковать разметку целиком:

1. **Согласие с прошлой разметкой на контрольных карточках.** Гейт записан до прогона:
   ≥ 0.80. Ниже — старые 65 меток и новые означают разное, складывать их в один набор
   нельзя `[inc-4]`.
2. **Слепой контроль на чистых ходах.** Карточки вида «чистая» взяты из решённых симуляций,
   где ни одно требование не провалено. Если разметка ставит «да» и там, она описывает
   фильтр добычи, а не положительные примеры. Планка та же, что прошла в прошлый раз:
   доля «да» на чистых заметно ниже, чем на кандидатах, с проверкой значимости.
3. **Согласие проходов между собой.** Прошлый раз 0.86–0.91. Разброс ниже 0.7 означал бы,
   что задача разметчику непонятна, и вердикт большинством собран из шума.

    python scripts/merge_markup_batch.py --проходы data/pass1.json data/pass2.json data/pass3.json
"""

from __future__ import annotations

import argparse
import json
import math
from pathlib import Path


def доля(k: int, n: int) -> float:
    return k / n if n else float("nan")


def z_двух_долей(k1: int, n1: int, k2: int, n2: int) -> float:
    """Значимость разницы двух долей. Нужна, чтобы «31 из 50 против 1 из 15» было
    утверждением, а не впечатлением."""
    if not n1 or not n2:
        return float("nan")
    p = (k1 + k2) / (n1 + n2)
    зн = math.sqrt(p * (1 - p) * (1 / n1 + 1 / n2))
    return (доля(k1, n1) - доля(k2, n2)) / зн if зн else float("nan")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--проходы", nargs="+", required=True)
    ap.add_argument("--ключ", default="data/markup_batch3_ключ.json")
    ap.add_argument("--карточки", default="data/markup_batch3.json")
    ap.add_argument("--out", default="data/markup_machine3.json")
    ap.add_argument("--гейт-согласия", type=float, default=0.80)
    ap.add_argument("--вид-из", default="data/markup_cards3_ключ.json",
                    help="ключ сборки, где записан вид карточки (кандидат/чистая)")
    ap.add_argument("--карточки-вида", default="data/markup_cards3.json",
                    help="карточки той же сборки — нужны, чтобы связать номер с id")
    a = ap.parse_args()

    ключ = json.loads(Path(a.ключ).read_text(encoding="utf-8"))
    # Два вида ключа. Партия с контрольными карточками из прошлой разметки хранит словарь
    # (источник, id, прошлый вердикт); обычная сборка `build_markup_cards.py` хранит просто
    # вид — «кандидат» или «чистая». Второй случай приводится к первому, чтобы дальше был
    # один код: контрольных карточек в нём нет, и проверка совместимости пропускается.
    if ключ and isinstance(next(iter(ключ.values())), str):
        карточки_вид = json.loads(Path(a.карточки).read_text(encoding="utf-8"))
        id_по_n = {str(к["n"]): к["id"] for к in карточки_вид}
        ключ = {n: {"источник": "новая", "id": id_по_n.get(n, ""),
                    "прошлый_вердикт": None, "вид": вид}
                for n, вид in ключ.items()}
    проходы = [json.loads(Path(p).read_text(encoding="utf-8")) for p in a.проходы]
    номера = sorted(ключ, key=int)

    неполные = [p for p, пр in zip(a.проходы, проходы) if len(пр) != len(номера)]
    if неполные:
        print(f"[ОТКАЗ] проходы неполны: {неполные} "
              f"(ожидалось {len(номера)} вердиктов в каждом)")
        return 2

    итог, согласий = {}, 0
    for n in номера:
        голоса = [str(пр.get(n, "")).strip().lower() for пр in проходы]
        да = sum(г == "da" for г in голоса)
        итог[n] = {"majority": "da" if да * 2 > len(голоса) else "net",
                   "голоса": голоса, **ключ[n]}
        согласий += len(set(голоса)) == 1

    # ── 3. Согласие проходов ─────────────────────────────────────────────────────────────
    print(f"единогласных карточек: {согласий}/{len(номера)} ({доля(согласий, len(номера)):.2f})")
    for i, пр in enumerate(проходы, 1):
        да = sum(1 for n in номера if str(пр.get(n, "")).lower() == "da")
        print(f"  проход {i}: «да» {да}/{len(номера)} ({доля(да, len(номера)):.2f})")
    попарно = []
    for i in range(len(проходы)):
        for j in range(i + 1, len(проходы)):
            с = sum(1 for n in номера
                    if str(проходы[i].get(n, "")).lower() == str(проходы[j].get(n, "")).lower())
            попарно.append(доля(с, len(номера)))
    print(f"  попарное согласие: {' · '.join(f'{x:.2f}' for x in попарно)}")

    # ── 1. Совместимость с прошлой разметкой ─────────────────────────────────────────────
    контроль = [n for n in номера if ключ[n]["источник"] == "контроль"]
    совпало = sum(1 for n in контроль if итог[n]["majority"] == ключ[n]["прошлый_вердикт"])
    с = доля(совпало, len(контроль))
    ок = с >= a.гейт_согласия if контроль else True
    if not контроль:
        print("\nсовместимость с прошлой разметкой не проверялась: контрольных карточек нет")
    else:
        print(f"\nсовместимость с прошлой разметкой: {совпало}/{len(контроль)} = {с:.2f} "
              f"(гейт ≥ {a.гейт_согласия}) — {'ПРОЙДЕН' if ок else 'ПРОВАЛЕН'}")
    if контроль and not ок:
        print("  ⚠ складывать старые 65 меток с новыми нельзя: они означают разное.")
        for n in контроль:
            if итог[n]["majority"] != ключ[n]["прошлый_вердикт"]:
                print(f"    карточка {n} ({ключ[n]['id']}): было "
                      f"{ключ[n]['прошлый_вердикт']}, стало {итог[n]['majority']}")

    # ── 2. Слепой контроль на чистых ─────────────────────────────────────────────────────
    # Вид карточки берётся из ключа, если он там есть (обычная сборка), иначе — из ключа
    # той сборки, откуда карточки пришли (партия с контрольными).
    по_id_вид = {}
    if not any("вид" in v for v in ключ.values()):
        путь_вид = Path(a.вид_из)
        if путь_вид.exists() and Path(a.карточки_вида).exists():
            вид_по_n = json.loads(путь_вид.read_text(encoding="utf-8"))
            карточки_ист = json.loads(Path(a.карточки_вида).read_text(encoding="utf-8"))
            по_id_вид = {к["id"]: вид_по_n.get(str(к["n"]), "") for к in карточки_ист}
    вид = lambda n: ключ[n].get("вид") or по_id_вид.get(ключ[n]["id"], "")  # noqa: E731
    новые = [n for n in номера if ключ[n]["источник"] == "новая"]
    канд = [n for n in новые if вид(n) == "кандидат"]
    чист = [n for n in новые if вид(n) == "чистая"]
    да_к = sum(1 for n in канд if итог[n]["majority"] == "da")
    да_ч = sum(1 for n in чист if итог[n]["majority"] == "da")
    if канд and чист:
        z = z_двух_долей(да_к, len(канд), да_ч, len(чист))
        print(f"\nслепой контроль: «да» на кандидатах {да_к}/{len(канд)} "
              f"({доля(да_к, len(канд)):.3f}), на заведомо чистых {да_ч}/{len(чист)} "
              f"({доля(да_ч, len(чист)):.3f}), z = {z:.2f}")
        if not (z > 1.64):
            print("  ⚠ разделение незначимо: разметка описывает фильтр добычи, а не дефект")
    else:
        print("\n⚠ слепой контроль не посчитан: вид новых карточек не восстановлен")

    Path(a.out).write_text(json.dumps(итог, ensure_ascii=False, indent=1), encoding="utf-8")
    да_всего = sum(1 for n in новые if итог[n]["majority"] == "da")
    print(f"\nзаписано {a.out}: новых карточек {len(новые)}, из них «да» {да_всего}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
