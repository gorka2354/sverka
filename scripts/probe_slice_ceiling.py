"""Знаменатель: в скольких случаях верный ответ вообще лежит в срезе.

Это НЕ гейт. Это число, без которого гейт бессмыслен. `[план 30.08.2026]` Требование
«модель подтверждает не менее 80% единиц» проверяет модель только если известно, в скольких
случаях подтвердить было чем. Если чанкер доносит верный ответ в 78% случаев, то гейт 0.80
проверяет чанкер, а модель к нему отношения не имеет.

Проба не делает ни одного вызова модели и считается за минуты. Она способна закрыть
направление бесплатно: если срез доносит верный ответ реже, чем в 75% случаев, слепое
заполнение пропуска мертво как основной канал до всякого прогона.

Разрез RU/EN обязателен. Корпус τ² английский, конкурсные данные русские, и калибровать
русский конвейер по английским числам нельзя.

    python scripts/probe_slice_ceiling.py
"""

from __future__ import annotations

import argparse
import collections
import json
import statistics
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from sverka.slices import отобрать, потолок  # noqa: E402
from sverka.units import извлечь  # noqa: E402


def набор_ru(путь: str) -> list[tuple[str, str]]:
    """Текстовая страта выданного сэмпла: ответы БЕЗ вызова инструмента, русские."""
    import pandas as pd
    d = pd.read_parquet(путь)
    без_вызова = d[~d["response"].astype(str).str.contains("TOOL_CALL", regex=False)]
    return [(str(r["prompt"]), str(r["response"])) for _, r in без_вызова.iterrows()]


def набор_en(путь: str, предел: int) -> list[tuple[str, str]]:
    строки = [json.loads(s) for s in Path(путь).read_text(encoding="utf-8").splitlines() if s.strip()]
    return [(str(r["prompt"]), str(r["response"])) for r in строки[:предел]]


def померить(пары, k_список=(3, 6)):
    итог = {}
    for k in k_список:
        исходы = collections.Counter()
        длины = []
        for контекст, ответ in пары:
            for ед in извлечь(ответ):
                исходы[потолок(контекст, ед, k=k)] += 1
                if k == k_список[0]:
                    длины.append(отобрать(контекст, ед, k=k).символов)
        n = sum(исходы.values())
        итог[k] = {
            "единиц": n,
            "нет_якорей": исходы["нет_якорей"] / n if n else 0.0,
            "есть_в_контексте": (исходы["в_срезе"] + исходы["нет_в_срезе"]) / n if n else 0.0,
            "есть_в_срезе": исходы["в_срезе"] / n if n else 0.0,
            # Главная величина: доля донесённых СРЕДИ тех, где было что доносить.
            "донесено_из_возможного": (
                исходы["в_срезе"] / (исходы["в_срезе"] + исходы["нет_в_срезе"])
                if (исходы["в_срезе"] + исходы["нет_в_срезе"]) else 0.0),
            "медиана_среза": statistics.median(длины) if длины else 0,
            "исходы": dict(исходы),
        }
    return итог


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--valid", default="data/raw/valid.parquet")
    ap.add_argument("--corpus", default="data/text_negatives.jsonl")
    ap.add_argument("--corpus-limit", type=int, default=60)
    args = ap.parse_args()

    наборы = []
    if Path(args.valid).exists():
        наборы.append(("RU — текстовая страта valid", набор_ru(args.valid)))
    if Path(args.corpus).exists():
        наборы.append(("EN — корпус τ²", набор_en(args.corpus, args.corpus_limit)))

    for имя, пары in наборы:
        итог = померить(пары)
        print(f"\n{'='*84}\n{имя}: {len(пары)} ответов\n{'='*84}")
        print(f"  {'k':>3} {'единиц':>7} {'нет якорей':>11} {'в контексте':>12} "
              f"{'в срезе':>9} {'донесено':>9} {'медиана среза':>14}")
        for k, v in итог.items():
            print(f"  {k:>3} {v['единиц']:>7} {v['нет_якорей']:>11.3f} "
                  f"{v['есть_в_контексте']:>12.3f} {v['есть_в_срезе']:>9.3f} "
                  f"{v['донесено_из_возможного']:>9.3f} {v['медиана_среза']:>11} симв")
        print(f"  исходы при k=6: {итог[6]['исходы']}")

    print(f"\n{'='*84}")
    print("КАК ЧИТАТЬ. «в срезе» — потолок для любой конструкции на срезах: выше него")
    print("не поднимется даже безупречная модель. Гейт на качество модели обязан быть")
    print("НИЖЕ этого числа, иначе он проверяет чанкер.")
    print("«донесено» — доля донесённых среди тех, где было что доносить: это качество")
    print("отбора кусков в чистом виде, без вклада вычисленных и выдуманных значений.")
    print("\nЕсли на RU «в срезе» ниже 0.75 при k=6 — слепое заполнение пропуска мертво")
    print("как основной канал, и вечер уходит на другую ветку без единого вызова модели.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
