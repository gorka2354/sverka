"""Точка входа-проба: превращает номер упавшего шага в ответ на вопрос о входе.

`[инцидент 28.08.2026]` Платформа не отдаёт ни текста ошибки, ни логов. Единственный
наблюдаемый выход прогона — номер шага, на котором он умер. Наблюдений накоплено три:

- падение на шаге **08** («Статус распаковки данных») — наш скрипт завершился ненулевым
  кодом. Так падал первый прогон, и лог тогда ещё отдавался: `UnicodeDecodeError` при
  чтении входа как UTF-8;
- падение на шаге **22** («Статус расчёта метрик») — наш скрипт завершился нулём, то есть
  отработал, но сопоставить его вывод с эталоном платформа не смогла. Так падают и
  диагностика, и «всё = 1»;
- отличить внутри шага 22 «мы прочитали вход не так» от «файл записан, но не подошёл»
  снаружи нельзя вовсе.

Отсюда конструкция этого файла. Он **проверяет собственное чтение** и, если хоть одна
проверка не сошлась, завершается единицей — то есть уводит прогон на шаг 08. Тогда:

    упало на 08  →  вход прочитан не так, как мы думаем; чинить чтение
    упало на 22  →  вход прочитан верно, дело в формате вывода или в сопоставлении

Это один бит за прогон, но бит, который разрезает пространство гипотез пополам, а не
подтверждает уже известное. Попытки при падении не расходуются, так что цена — время.

Проверки подобраны так, чтобы каждая была почти наверняка верна при исправном чтении:
непустой набор строк, выбранный столбец идентификаторов заполнен, значения уникальны и
коротки. Последнее ловит самый неприятный из вероятных сбоев — когда за идентификаторы
принят столбец с текстом контекста на тридцать тысяч символов.

**Метки намеренно двух видов.** Прогоны, дошедшие до шага 22, отправляли файл, где метка 1
стоит в каждой строке без исключения. Это единственное свойство наших сабмитов, которое мы
не меняли ни разу.

Механизм, из-за которого константный вектор роняет расчёт: `precision_recall_fscore_support`
по умолчанию считает метрики **на каждый класс отдельно** (`average=None`), и для класса,
которому не назначено ни одного предсказания, precision не определён. В обычном режиме это
предупреждение, но под `warnings.simplefilter("error")` или в рукописной агрегации это уже
исключение либо деление на ноль. `[замер: sklearn 1.9.0]` Само по себе значение
`zero_division="raise"` тут ни при чём — такого значения у параметра нет, sklearn отвергает
его как невалидное независимо от предсказаний.

Гипотеза закрывается тем, что примерно каждой десятой строке ставится ноль. Строка
выбирается по контрольной сумме идентификатора, а не по номеру: если файл отсортирован по
классу, разбиение по чётности номера коррелировало бы с ответом и испортило бы замер.

Измерение при этом не теряется. Правило не смотрит на содержимое, поэтому его Precision
равен доле положительных в наборе — той самой величине, ради которой и планировался
первый содержательный сабмит, — а Recall выходит около 0.9. Шум оценки доли при этом
даже меньше, чем дало бы правило «всё = 1» с его нулевым Recall-риском.

Дополнительно закрыты два риска, которые сами по себе объясняли бы падение на 22:

- **запуск под mpirun.** В логе первого прогона были префиксы рангов `[1,0]<stderr>`.
  Если рангов больше одного, каждый выполняет этот скрипт и каждый пишет в один и тот же
  файл вывода — получится каша. Пишет только нулевой ранг;
- **неатомарная запись.** Файл собирается рядом и переименовывается одним движением,
  чтобы читатель не мог застать его недописанным.

Вывод в stdout и stderr убран полностью: логов всё равно нет, а вероятность, что конвейер
считает непустой stderr признаком сбоя, ненулевая и стоит ноль.
"""

