def raise_csv_field_limit() -> None:
    """Поднять лимит длины поля до максимума, который принимает эта сборка Python.

    Дефолт 131 072 меньше максимального prompt выданного сэмпла (233 104 символа), так что
    без этого чтение падает ровно на длинных примерах. `sys.maxsize` при этом переполняет
    C long на части платформ, поэтому спускаемся от 2**31-1.
    """
    lim = 2**31 - 1
    while True:
        try:
            csv.field_size_limit(lim)
            return
        except OverflowError:
            lim //= 2


def read_table(path: str):
    """Прочитать вход, опознав формат по сигнатуре, а не по расширению.

    Платформа передаёт путь как `test.csv`, но первые байты боевого файла совпали с
    сигнатурой parquet: байт `0xf8` на седьмой позиции — ровно то, что стоит там в
    заголовке parquet, и ровно на этом байте упало наивное чтение в UTF-8.

    Третьим значением возвращается сам датафрейм, если вход был parquet. Он нужен, чтобы
    писать выход, не трогая тип столбца идентификаторов: `str()` у float-идентификатора
    дал бы `12345.0`, и сопоставление с эталоном развалилось бы молча. В выданном сэмпле
    столбец строковый `[замер]`, но на боевом наборе это не гарантировано.
    """
    with open(path, "rb") as f:
        head = f.read(8)

    if head.startswith(b"PAR1"):
        # Ленивый импорт, а не объявленная зависимость: объявить pandas нельзя — без
        # интернета `pip install .` упадёт раньше, чем скрипт что-либо сделает.
        import pandas as pd
        df = pd.read_parquet(path)
        return df.to_dict("records"), [str(c) for c in df.columns], df

    if head.startswith(b"\x1f\x8b"):
        import gzip
        with gzip.open(path, "rb") as f:
            raw = f.read()
    else:
        with open(path, "rb") as f:
            raw = f.read()

    for enc in ENCODINGS:
        try:
            text = raw.decode(enc)
        except (UnicodeDecodeError, LookupError):
            continue
        try:
            delim = csv.Sniffer().sniff(text[:65536], delimiters=",;\t|").delimiter
        except Exception:  # noqa: BLE001
            delim = ","
        try:
            reader = csv.DictReader(io.StringIO(text), delimiter=delim)
            cols = list(reader.fieldnames or [])
            rows = list(reader)
        except Exception:  # noqa: BLE001
            continue
        if cols:
            return rows, cols, None
    return [], [], None


def pick_id_column(rows, cols):
    """Выбрать столбец идентификаторов, не полагаясь на то, что он называется `id`.

    Прежний код брал первый столбец, если точного имени не нашлось. Это тихо приводило бы
    к тому, что за идентификаторы принят текст контекста, файл предсказаний раздувается до
    сотен мегабайт, и сопоставление с эталоном падает без единого сообщения.
    """
    if "id" in cols:
        return "id"
    lowered = {c.lower(): c for c in cols}
    for name in ("id", "sample_id", "example_id", "row_id", "uid", "index"):
        if name in lowered:
            return lowered[name]
    # Иначе — самый короткий столбец, значения которого уникальны и непусты.
    best, best_len = None, None
    probe = rows[: min(len(rows), 500)]
    for c in cols:
        vals = [str(r.get(c, "")).strip() for r in probe]
        if not vals or any(not v for v in vals) or len(set(vals)) != len(vals):
            continue
        longest = max(len(v) for v in vals)
        if longest > MAX_ID_LEN:
            continue
        if best_len is None or longest < best_len:
            best, best_len = c, longest
    return best


def _данные_ответ(question: str, rows, cols) -> bool | None:
    """Вопросы о САМОМ ТЕСТОВОМ НАБОРЕ, а не об образе. `None` — вопрос не отсюда.

    Зачем это здесь. `[измерено 31.08.2026]` Выданный сэмпл `valid.parquet` ввёл
    в заблуждение четыре раза подряд — балансом классов, стратами, длиной ответа и долей
    ответов с проверяемыми единицами (0.348 против ≈0 на боевом наборе). Значит любая
    величина, снятая с сэмпла, — гипотеза. При этом свойства ВХОДА не зависят от меток,
    а отказной прогон лимит не тратит `[девять прогонов 28–30.08, счётчик держался на 10]`.
    Отсюда правило распределения бюджета: всё, что вычислимо из входа, меряется бесплатно
    на настоящей популяции, и ни один невозвратный слот на это не тратится.

    Ответ кодируется кодом возврата: «да» → 0 → шаг 22, «нет» → 1 → шаг 08. Оба исхода —
    отказ, потому что выход пишется текстовым CSV и с эталоном не сопоставляется. ⚠️ Это
    свойство обязано сохраняться НАМЕРЕННО: стоит собрать probe с parquet-выходом, и ответ
    «да» превратится в засчитанный сабмит, съевший слот.
    """
    ответы = [str(r.get("response", "") or "") for r in rows] if rows else []
    if not ответы:
        return False

    if question == "parse_health":
        # Здоровье разбора транскрипта. Первый вопрос по порядку важности: если формат
        # на боевом наборе отличается от известных трёх, любая модельная работа читает
        # мусор, и это не проверялось ни разу.
        try:
            from sverka.transcript import parse_response, parse_transcript
        except Exception:  # noqa: BLE001
            return False
        живых = 0
        for r in rows:
            try:
                tr = parse_transcript(str(r.get("prompt", "") or ""), strict=False)
                turn = parse_response(str(r.get("response", "") or ""), strict=False)
                здоров = bool(tr.health and tr.health.ok)
                if здоров and (turn.text or turn.tool_calls):
                    живых += 1
            except Exception:  # noqa: BLE001
                continue
        return живых >= 0.95 * len(rows)

    if question == "n_gt_800":
        # Размер набора. Из Precision первого сабмита известно N ≥ 548; целочисленность
        # разложения лидерборда допускает 548 и кратные. Бит режет бюджет времени вдвое.
        return len(rows) > 800

    if question == "units_heavy":
        # Доля ответов с тремя и более проверяемыми единицами. От неё зависит, воскресает
        # ли семейство «модель читает контекст»: проекция судьи 0.123 держится на весе
        # «91% лёгких ответов», взятом с сэмпла, а сэмпл по этому признаку уже опровергнут.
        try:
            from sverka.units import извлечь
        except Exception:  # noqa: BLE001
            return False
        текстовые = [t for t in ответы if "TOOL_CALL" not in t]
        if not текстовые:
            return False
        тяжёлых = sum(1 for t in текстовые if len(извлечь(t)) >= 3)
        return тяжёлых > 0.30 * len(текстовые)

    if question == "median_len_gt_500":
        д = sorted(len(t) for t in ответы)
        return д[len(д) // 2] > 500

    if question == "tool_gt_200":
        return sum(1 for t in ответы if "TOOL_CALL" in t) > 200

    return None


def напечатать_отчёт(rows, cols) -> None:
    """Полная диагностика тестового набора в stdout — вместо одного бита за прогон.

    `[открыто 31.08.2026]` Считалось, что платформа логов не отдаёт. Это неверно: у каждого
    шага в интерфейсе есть ссылка «Logs» на объектное хранилище, и лог доступен по прямому
    URL. Наш вывод там не появлялся ровно потому, что мы сами его отключили — в шапке этого
    файла записано «вывод в stdout и stderr убран полностью».

    Значит канал не двоичный, а текстовый: один отказной прогон (код возврата 1, попытка
    возвращается) приносит столько чисел, сколько напечатаем. Пять заготовленных вопросов —
    здоровье разбора, доля тяжёлых ответов, медиана длины, размер набора, размер страты —
    закрываются этим отчётом разом, и остаётся ещё место для того, о чём мы не догадались
    спросить заранее.

    Печать обёрнута так, чтобы не уронить прогон раньше времени: любая ошибка внутри
    выводится строкой и работа продолжается.
    """
    def строка(*части):
        try:
            print("[sverka]", *части, flush=True)
        except Exception:  # noqa: BLE001
            pass

    try:
        строка("строк:", len(rows), "| колонки:", cols)
        отв = [str(r.get("response", "") or "") for r in rows]
        пром = [str(r.get("prompt", "") or "") for r in rows]
        if not отв:
            return
        дл_о = sorted(len(x) for x in отв)
        дл_п = sorted(len(x) for x in пром)
        def кв(д, q):
            return д[min(len(д) - 1, int(len(д) * q))]
        строка("ответ симв: мин", дл_о[0], "p25", кв(дл_о, .25), "медиана", кв(дл_о, .5),
               "p75", кв(дл_о, .75), "p90", кв(дл_о, .9), "макс", дл_о[-1])
        строка("промпт симв: медиана", кв(дл_п, .5), "p90", кв(дл_п, .9), "макс", дл_п[-1])

        # Маркеры формата: какой из трёх известных вариантов пришёл на самом деле.
        for м in ("⟦SYSTEM⟧", "⟦USER⟧", "⟦ASSISTANT", "TOOL_CALL", "TOOL_RESPONSE",
                  "⟦ASSISTANT_TOOL_CALL", "⟦TOOL_RESULT"):
            строка(f"маркер {м}: в промптах", sum(1 for x in пром if м in x),
                   "| в ответах", sum(1 for x in отв if м in x))

        кир = sum(1 for x in отв if sum(1 for c in x if "а" <= c.lower() <= "я") > 0.3 * max(len(x), 1))
        строка("ответов с долей кириллицы > 0.3:", кир, "из", len(отв))

        try:
            from sverka.units import извлечь
            по_единицам = [len(извлечь(x)) for x in отв]
            строка("единиц в ответе: 0 →", sum(1 for n in по_единицам if n == 0),
                   "| 1-2 →", sum(1 for n in по_единицам if 1 <= n <= 2),
                   "| 3+ →", sum(1 for n in по_единицам if n >= 3),
                   "| медиана", sorted(по_единицам)[len(по_единицам) // 2])
        except Exception as e:  # noqa: BLE001
            строка("units НЕДОСТУПЕН:", type(e).__name__, str(e)[:200])

        try:
            from sverka.transcript import parse_response, parse_transcript
            здоров = плохих = 0
            причины = {}
            for r in rows[:400]:
                try:
                    tr = parse_transcript(str(r.get("prompt", "") or ""), strict=False)
                    turn = parse_response(str(r.get("response", "") or ""), strict=False)
                    if tr.health and tr.health.ok and (turn.text or turn.tool_calls):
                        здоров += 1
                    else:
                        плохих += 1
                        к = str(tr.health) if tr.health else "health=None"
                        причины[к] = причины.get(к, 0) + 1
                except Exception as e:  # noqa: BLE001
                    плохих += 1
                    причины["ИСКЛ " + type(e).__name__] = причины.get("ИСКЛ " + type(e).__name__, 0) + 1
            строка("разбор: здоров", здоров, "нездоров", плохих, "из", min(len(rows), 400))
            for к, n in sorted(причины.items(), key=lambda x: -x[1])[:6]:
                строка("  причина ×", n, ":", к)
        except Exception as e:  # noqa: BLE001
            строка("transcript НЕДОСТУПЕН:", type(e).__name__, str(e)[:200])

        строка("первые id:", [str(r.get("id", ""))[:40] for r in rows[:3]])
    except Exception as e:  # noqa: BLE001
        строка("ОТЧЁТ УПАЛ:", type(e).__name__, str(e)[:300])


def answer_probe(question: str, rows=None, cols=None) -> bool:
    """Ответить на вопрос об образе платформы или о тестовом наборе.

    Ни при каких условиях не бросает исключений: любая сложность здесь превратила бы «нет»
    в «наш код сломался», а различить эти два исхода снаружи нечем.
    """
    if question == "none":
        return True
    try:
        из_данных = _данные_ответ(question, rows or [], cols or [])
    except Exception:  # noqa: BLE001
        return False
    if из_данных is not None:
        return из_данных
    if question == "package_installed":
        # Установился ли НАШ пакет. Отвечает на главный вопрос: выполняет ли платформа
        # `pip install .` успешно. Если нет — зависимости объявлять бессмысленно в принципе,
        # а раскладка без pyproject.toml становится обязательной.
        try:
            import sverka  # noqa: F401
            return True
        except Exception:  # noqa: BLE001
            return False
    if question == "internet":
        import socket
        try:
            socket.create_connection(("pypi.org", 443), timeout=5).close()
            return True
        except Exception:  # noqa: BLE001
            return False
    if question == "cuda":
        try:
            import torch
            return bool(torch.cuda.is_available())
        except Exception:  # noqa: BLE001
            return False
    if question == "gpu_h100":
        try:
            import torch
            return "H100" in torch.cuda.get_device_name(0)
        except Exception:  # noqa: BLE001
            return False
    # Остальные вопросы — «есть ли такой модуль в образе».
    модуль = {"sklearn": "sklearn", "hf": "huggingface_hub"}.get(question, question)
    try:
        __import__(модуль)
        return True
    except Exception:  # noqa: BLE001
        return False


def mpi_rank_and_size():
    """Ранг и размер MPI-группы, если прогон запущен через mpirun.

    В логе первого прогона стояли префиксы вида `[1,0]<stderr>` — так помечает вывод
    Open MPI. Если процессов больше одного, каждый выполнит этот скрипт и каждый попытается
    писать в один и тот же файл. Пишет только нулевой.
    """
    rank = size = None
    for var in ("OMPI_COMM_WORLD_RANK", "PMI_RANK", "PMIX_RANK", "SLURM_PROCID",
                "MV2_COMM_WORLD_RANK", "MPI_LOCALRANKID"):
        if os.environ.get(var):
            try:
                rank = int(os.environ[var])
                break
            except ValueError:
                pass
    for var in ("OMPI_COMM_WORLD_SIZE", "PMI_SIZE", "PMIX_SIZE", "SLURM_NTASKS",
                "MV2_COMM_WORLD_SIZE", "WORLD_SIZE"):
        if os.environ.get(var):
            try:
                size = int(os.environ[var])
                break
            except ValueError:
                pass
    return (0 if rank is None else rank), (1 if size is None else size)


def make_labels(ids):
    """Разметить строки так, чтобы в файле гарантированно были оба класса.

    Правило не смотрит на содержимое ответа вовсе, поэтому его Precision равен доле
    положительных примеров в наборе — величине, которую иначе не узнать. Разбиение идёт
    по контрольной сумме идентификатора: `crc32` из стандартной библиотеки детерминирован
    между запусками, в отличие от встроенного `hash`, у которого соль случайна.
    """
    labels = [0 if zlib.crc32(x.encode("utf-8")) % ZERO_EVERY == 0 else 1 for x in ids]
    if len(set(labels)) < 2 and labels:
        # Страховка на вырожденном наборе: на десятке строк все контрольные суммы могли
        # лечь по одну сторону, а вся затея в том, чтобы классов было ровно два.
        labels[0] = 1 - labels[0]
    return labels


def write_predictions(path: str, ids, labels, frame=None, id_col=None) -> None:
    """Записать файл предсказаний атомарно: сначала рядом, потом переименованием.

    Атомарность нужна на случай запуска несколькими процессами MPI: читатель не должен
    застать файл недописанным. Определение ранга опирается на переменные окружения и может
    не сработать под незнакомым лаунчером, поэтому переименование — вторая линия обороны.
    """
    d = os.path.dirname(os.path.abspath(path))
    if d:
        os.makedirs(d, exist_ok=True)
    tmp = os.path.abspath(path) + ".part"

    if OUTPUT_FORMAT == "parquet":
        import pandas as pd
        if frame is not None and id_col is not None:
            # Столбец идентификаторов берётся из входного датафрейма КАК ЕСТЬ, без
            # приведения к строке: сохраняется исходный тип, и отпадает риск получить
            # `12345.0` там, где эталон ждёт целое.
            out = pd.DataFrame({"id": frame[id_col].values, "label": labels})
        else:
            out = pd.DataFrame({"id": ids, "label": labels})
        out["label"] = out["label"].astype("int64")
        out.to_parquet(tmp, index=False)
    else:
        with open(tmp, "w", encoding="utf-8", newline="") as f:
            w = csv.writer(f, lineterminator="\n")
            if WRITE_HEADER:
                w.writerow(["id", "label"])
            w.writerows(zip(ids, labels))

    os.replace(tmp, os.path.abspath(path))


def main() -> int:
    ap = argparse.ArgumentParser(add_help=False)
    ap.add_argument("--input", default=None)
    ap.add_argument("--output", default=None)
    args, _unknown = ap.parse_known_args()

    # Ниже — те самые проверки, ради которых файл существует. Любая несошедшаяся уводит
    # прогон на шаг 08 и тем сообщает: дело во входе, а не в формате вывода.
    if not args.input or not args.output:
        return 1
    if not os.path.exists(args.input):
        return 1

    raise_csv_field_limit()
    try:
        rows, cols, frame = read_table(args.input)
    except Exception:  # noqa: BLE001
        return 1

    if not rows or not cols:
        return 1

    id_col = pick_id_column(rows, cols)
    if id_col is None:
        return 1

    ids = [str(r.get(id_col, "")).strip() for r in rows]
    if any(not x for x in ids):
        return 1
    if max(len(x) for x in ids) > MAX_ID_LEN:
        return 1
    # Повторяющиеся идентификаторы намеренно НЕ считаются отказом. В выданном сэмпле их нет
    # `[замер: 0 дублей на 46 строках]`, но один диалог там представлен двумя ходами, и на
    # тестовом наборе схема идентификации вполне может допускать повтор. Отказ по дублю
    # увёл бы прогон на шаг 08, а этот шаг у нас означает «вход прочитан неверно» — то есть
    # мы получили бы ответ на вопрос, которого не задавали.

    rank, size = mpi_rank_and_size()
    if size > 1 and rank != 0:
        # Не ошибка: писать должен ровно один процесс. Остальные молча выходят нулём.
        return 0

    try:
        labels = make_labels(ids)
        write_predictions(args.output, ids, labels, frame, id_col)
    except Exception:  # noqa: BLE001
        return 1

    # Опрос образа выполняется ПОСЛЕ записи предсказаний: ответ «нет» не должен лишать нас
    # валидного файла на случай, если платформа его всё же прочитает.
    if PROBE_QUESTION == "report":
        напечатать_отчёт(rows, cols)
        # `[лог 31.08.2026]` Шаг 10 конвейера называется «работа кода инференса
        # (ОГРАНИЧЕННЫЙ сет)» и подаёт наш же выданный сэмпл: 46 строк с колонками
        # label и explanation. Боевой набор приходит на СЛЕДУЮЩЕМ шаге. Значит на
        # ограниченном сете надо вернуть НОЛЬ и пройти дальше, иначе отчёт о настоящих
        # данных мы не увидим никогда.
        сэмпл = "label" in (cols or []) or len(rows) <= 60
        if сэмпл and not ОТЧЁТ_НА_СЭМПЛЕ:
            print("[sverka] это ограниченный сет — пропускаем дальше", flush=True)
            return 0
        if сэмпл:
            # Лог публикуется ТОЛЬКО для ограниченного сета, поэтому проверять здоровье
            # импорта надо здесь и падать здесь же, иначе результат проверки не увидеть.
            print("[sverka] отчёт по ограниченному сету, падаем намеренно", flush=True)
            return 1
        # На боевом наборе печатаем отчёт и падаем намеренно: отказ возвращает попытку.
        print("[sverka] это БОЕВОЙ набор — отчёт выше, завершаемся отказом", flush=True)
        return 1
    return 0 if answer_probe(PROBE_QUESTION, rows, cols) else 1


if __name__ == "__main__":
    sys.exit(main())
