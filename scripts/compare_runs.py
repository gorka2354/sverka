"""Парное сравнение двух прогонов судьи по одним и тем же примерам.

Зачем парно, а не по средним. `[урок проекта]` Средние по группам трижды вводили в
заблуждение: разница могла возникнуть от того, что в группах разный материал. Здесь материал
один и тот же, меняется одно условие, поэтому смотреть надо на **переходы конкретных строк**:
сколько ложных исправилось, сколько верных сломалось, и в какой группе это произошло.

Ключевой разрез — по тому, был ли промпт усечён в БАЗОВОМ прогоне: изменения должны
происходить именно там, а группа «целые» служит контролем. Если она тоже поехала, значит
прогон недетерминирован, и сравнивать нечего.

    python scripts/compare_runs.py --база data/judge_27b.jsonl --новый data/judge_27b_ctx48k.jsonl
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path


def читать(путь: str) -> dict:
    return {z["id"]: z for z in (json.loads(s) for s in
                                 Path(путь).read_text(encoding="utf-8").splitlines() if s.strip())}


def ставки(строки) -> tuple[float, float, int, int]:
    поз = [x for x in строки if x["label"] == 1]
    отр = [x for x in строки if x["label"] == 0]
    tpr = sum(x["score"] >= 0.5 for x in поз) / len(поз) if поз else float("nan")
    fpr = sum(x["score"] >= 0.5 for x in отр) / len(отр) if отр else float("nan")
    return tpr, fpr, len(поз), len(отр)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--база", required=True)
    ap.add_argument("--новый", required=True)
    ap.add_argument("--подробно", action="store_true", help="печатать каждый переход")
    a = ap.parse_args()

    база, новый = читать(a.база), читать(a.новый)
    общие = [i for i in новый if i in база]
    if not общие:
        print("[ОТКАЗ] у прогонов нет общих примеров"); return 2

    условия = lambda d, i: (d[i].get("модель"), d[i].get("окно"),  # noqa: E731
                            d[i].get("бюджет_символов"), d[i].get("спасение_якорей"))
    print(f"сравнение по {len(общие)} общим примерам из {len(база)} и {len(новый)}")
    print(f"  база:  модель/окно/бюджет/якоря = {условия(база, общие[0])}")
    print(f"  новый: модель/окно/бюджет/якоря = {условия(новый, общие[0])}")

    исправлено, сломано, без_изменений = [], [], 0
    for i in общие:
        б, н = база[i], новый[i]
        сраб_б, сраб_н = б["score"] >= 0.5, н["score"] >= 0.5
        if сраб_б == сраб_н:
            без_изменений += 1
            continue
        верно_б = сраб_б == bool(б["label"])
        (сломано if верно_б else исправлено).append((i, б, н))

    print(f"\n  исправлено: {len(исправлено)}   сломано: {len(сломано)}   "
          f"без изменений: {без_изменений}")

    for имя, список in (("ИСПРАВЛЕНО", исправлено), ("СЛОМАНО", сломано)):
        if not список:
            continue
        усечённых = sum(1 for _, б, _ in список if б.get("усечено"))
        print(f"\n  {имя} ({len(список)}), из них было усечено в базе: {усечённых}")
        if a.подробно:
            for i, б, н in список:
                print(f"    {i[:40]:<40} метка={б['label']} "
                      f"{б['grade']}({б['score']:.2f}) → {н['grade']}({н['score']:.2f}) "
                      f"усеч {б.get('усечено')}→{н.get('усечено')}")

    print("\n  ставки по группам базового прогона:")
    print(f"  {'группа':<12} {'поз':>4} {'отр':>4} {'полнота б→н':>16} {'ложных б→н':>16}")
    for имя, отб in (("целые", False), ("усечённые", True)):
        сб = [база[i] for i in общие if bool(база[i].get("усечено")) is отб]
        сн = [новый[i] for i in общие if bool(база[i].get("усечено")) is отб]
        if not сб:
            continue
        тб, фб, п, о = ставки(сб)
        тн, фн, _, _ = ставки(сн)
        print(f"  {имя:<12} {п:>4} {о:>4} {тб:>7.3f} → {тн:<7.3f} {фб:>7.3f} → {фн:<7.3f}")
    print("\n  ⚠ группа «целые» — контроль: её промпты не менялись, и расхождение там "
          "означает недетерминированность прогона, а не эффект условия.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
