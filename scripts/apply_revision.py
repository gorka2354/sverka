"""Применить ревизию меток к корпусу — с сохранением исходной метки и следа правки.

Зачем отдельный скрипт, а не правка руками. `[урок проекта]` Корпус — единственная опора
всех измерений, и любая правка в нём меняет ВСЕ прошлые числа задним числом. Поэтому:

1. Исходная метка не затирается, а переезжает в поле `label_исходная`.
2. Каждая правка несёт причину и того, кто её предложил, — чтобы через неделю можно было
   спросить «почему здесь ноль» и получить ответ, а не догадку.
3. Правки принимаются ТОЛЬКО двусторонним списком. Односторонняя чистка (снять часть
   единиц, не проверив нули) поднимает полноту искусственно: сжимается знаменатель,
   а числитель остаётся. Скрипт отказывается работать, если ему дали правки в одну сторону
   и не передали `--односторонне-осознанно`.

    python scripts/apply_revision.py --правки data/revision.json \\
        --вход data/markup_all_for_judge.jsonl --выход data/markup_revised.jsonl
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path


def читать(путь: str) -> list[dict]:
    return [json.loads(s) for s in Path(путь).read_text(encoding="utf-8").splitlines()
            if s.strip()]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--правки", required=True,
                    help="json: {id: {'label': 0|1, 'причина': str, 'кем': str}}")
    ap.add_argument("--вход", default="data/markup_all_for_judge.jsonl")
    ap.add_argument("--выход", default="data/markup_revised.jsonl")
    ap.add_argument("--односторонне-осознанно", action="store_true",
                    help="разрешить правки в одну сторону; по умолчанию это отказ")
    a = ap.parse_args()

    правки = json.loads(Path(a.правки).read_text(encoding="utf-8"))
    строки = читать(a.вход)
    по_id = {z["id"]: z for z in строки}

    неизвестные = [i for i in правки if i not in по_id]
    if неизвестные:
        print(f"[ОТКАЗ] в правках {len(неизвестные)} id, которых нет в корпусе: "
              f"{неизвестные[:5]}")
        return 2

    сняли = sum(1 for i, п in правки.items() if по_id[i]["label"] == 1 and п["label"] == 0)
    добавили = sum(1 for i, п in правки.items() if по_id[i]["label"] == 0 and п["label"] == 1)
    без_изменений = len(правки) - сняли - добавили

    print(f"правок: {len(правки)} — снять единицу {сняли}, поставить единицу {добавили}, "
          f"подтверждено без изменений {без_изменений}")

    if (сняли and not добавили) and not a.односторонне_осознанно:
        print("[ОТКАЗ] правки только в одну сторону: снимаются единицы, но ни один ноль "
              "не пересмотрен. Так полнота растёт за счёт сжатия знаменателя, а не за счёт "
              "пойманных примеров. Проверьте отрицательные или передайте "
              "--односторонне-осознанно, если это сознательное решение.")
        return 2

    изменено = 0
    for z in строки:
        п = правки.get(z["id"])
        if not п or п["label"] == z["label"]:
            continue
        z["label_исходная"] = z["label"]
        z["label"] = int(п["label"])
        z["правка_причина"] = п.get("причина", "")
        z["правка_кем"] = п.get("кем", "")
        изменено += 1

    Path(a.выход).write_text("".join(json.dumps(z, ensure_ascii=False) + "\n" for z in строки),
                             encoding="utf-8")
    поз = sum(z["label"] for z in строки)
    print(f"записано {len(строки)} строк в {a.выход}: изменено {изменено}, "
          f"положительных {поз} (было {поз - добавили + сняли}), отрицательных {len(строки) - поз}")
    print("  исходные метки сохранены в поле label_исходная")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
