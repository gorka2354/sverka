"""Тесты клиента ollama — защита от тихой обрезки входа и от потери `num_ctx` в запросе.

Смысл: `[замер 31.08.2026]` четыре записанных вывода проекта оказались измерением обрезки,
а не модели, потому что ollama молча урезала промпт, а ответ приходил валидным по форме.

Первая редакция этих тестов свою работу не делала. Проверка мутацией `[ревью 31.08.2026]`:
из `options` убрали `"num_ctx"` — то есть буквально воспроизвели аварию — и все одиннадцать
тестов остались зелёными, потому что поддельный `urlopen` игнорировал аргументы и тела
запроса не видел никто. Поэтому здесь проверяется ДВА разных предмета:

1. **что уходит на сервер** — `num_ctx` в `options`, `stream`, `think`, `format`;
2. **как разбирается ответ** — распознавание обрезки на числах из реальных замеров.

Сети тесты не требуют.
"""

from __future__ import annotations

import contextlib
import json

import pytest

from sverka.ollama import (
    ДОПУСК_ПОЛОВИНЫ,
    СИМВОЛОВ_НА_ТОКЕН_ПОТОЛОК,
    ВходОбрезан,
    Ответ,
    проверить_доставку,
    спросить,
)

# ── Что уходит на сервер ─────────────────────────────────────────────────────────────────


class _Перехват:
    """Поддельный `urlopen`, который ЧИТАЕТ запрос. Без этого тесты не видят тела и
    пропускают ровно ту ошибку, ради которой написаны."""

    def __init__(self, дошло=100, причина_конца="stop"):
        self.тело = None
        self.url = None
        self._дошло = дошло
        self._причина = причина_конца

    def __call__(self, req, *_a, **_kw):
        self.тело = json.loads(req.data.decode("utf-8"))
        self.url = req.full_url
        причина, дошло = self._причина, self._дошло

        @contextlib.contextmanager
        def открыть():
            class Тело:
                @staticmethod
                def read():
                    return json.dumps({"message": {"content": "{}"},
                                       "prompt_eval_count": дошло,
                                       "eval_count": 5,
                                       "done_reason": причина}).encode("utf-8")
            yield Тело()

        return открыть()


def _вызвать(monkeypatch, **kw):
    п = _Перехват(**{k: kw.pop(k) for k in ("дошло", "причина_конца") if k in kw})
    monkeypatch.setattr("sverka.ollama.urllib.request.urlopen", п)
    о = спросить("http://х", "модель", "система", "вопрос", **kw)
    return п, о


def test_num_ctx_реально_уходит_в_options(monkeypatch):
    """Главный тест файла: он обязан краснеть, если `num_ctx` пропадёт из запроса."""
    п, _ = _вызвать(monkeypatch, num_ctx=16384)
    assert п.тело["options"]["num_ctx"] == 16384


def test_num_predict_и_температура_уходят_как_заданы(monkeypatch):
    п, _ = _вызвать(monkeypatch, num_ctx=8192, num_predict=200, температура=0.0)
    assert п.тело["options"]["num_predict"] == 200
    assert п.тело["options"]["temperature"] == 0.0


def test_поток_всегда_выключен(monkeypatch):
    """Разбор ответа рассчитан на цельный JSON, а не на поток чанков."""
    п, _ = _вызвать(monkeypatch, num_ctx=8192)
    assert п.тело["stream"] is False


def test_think_не_кладётся_когда_не_просят(monkeypatch):
    """`[замер 30.08.2026]` На gpt-oss:20b ответ пуст ИМЕННО с `think: false`, поэтому
    отсутствие поля и `false` — разные режимы, а не одно и то же."""
    п, _ = _вызвать(monkeypatch, num_ctx=8192, думать=None)
    assert "think" not in п.тело


def test_think_false_кладётся_когда_просят(monkeypatch):
    """`[замер 30.08.2026]` На qwen3.5 без выключения вся квota вывода уходит в рассуждение."""
    п, _ = _вызвать(monkeypatch, num_ctx=8192, думать=False)
    assert п.тело["think"] is False


def test_схема_уходит_в_format(monkeypatch):
    схема = {"type": "object", "properties": {"значение": {"type": "string"}}}
    п, _ = _вызвать(monkeypatch, num_ctx=8192, формат=схема)
    assert п.тело["format"] == схема


def test_format_не_кладётся_пустым(monkeypatch):
    """Пустой `format` у части сборок ломает декодирование — поля не должно быть вовсе."""
    п, _ = _вызвать(monkeypatch, num_ctx=8192)
    assert "format" not in п.тело


def test_причина_конца_доезжает_до_ответа(monkeypatch):
    """`done_reason == "length"` означает оборванный JSON, который разборщик молча отдаст
    как «модель не ответила»."""
    _, о = _вызвать(monkeypatch, num_ctx=8192, причина_конца="length")
    assert о.вывод_оборван and о.причина_конца == "length"
    _, о2 = _вызвать(monkeypatch, num_ctx=8192, причина_конца="stop")
    assert not о2.вывод_оборван


# ── Как распознаётся обрезка ─────────────────────────────────────────────────────────────


@pytest.mark.parametrize("num_ctx,дошло", [
    (4096, 2050), (8192, 4098), (16384, 8194), (20480, 10242), (24576, 12290),
])
def test_половина_окна_это_обрезка(num_ctx, дошло):
    """`[замер, девять точек]` При переполнении ollama читает ровно `num_ctx//2 + 2`.

    Плотность здесь взята 3.0 симв/токен — та, что реально встречается на самых длинных
    промптах судьи. Прежний потолок 7 на ней молчал: половинное чтение даёт 6.0.
    """
    символов = int(дошло * 2 * 3.0)
    assert "половина окна" in проверить_доставку(символов, дошло, num_ctx)


def test_прежний_потолок_семь_пропускал_эту_обрезку():
    """Регрессия на конкретную дыру: при плотности 3.0 обрезка вдвое даёт 6.0 симв/токен."""
    символов, дошло, num_ctx = 61428, 10242, 20480
    assert символов / дошло < 7, "иначе тест проверяет не то, что задуман"
    assert проверить_доставку(символов, дошло, num_ctx)


def test_настоящая_обрезка_из_замера_ловится():
    """Промпт 21 038 символов при окне 4096 прошёл как 2050 токенов — тот самый случай."""
    assert проверить_доставку(символов=21038, дошло=2050, num_ctx=4096)


def test_честный_вызов_из_того_же_замера_проходит():
    """Тот же промпт при окне 16384 прочитан целиком: 10 571 токен, ответ верный."""
    assert проверить_доставку(символов=21038, дошло=10571, num_ctx=16384) == ""


@pytest.mark.parametrize("символов,дошло,num_ctx", [
    (56490, 16912, 24576),   # контрольный вызов на 1200 строк данных
    (14181, 4432, 16384),    # медиана срезов probe_cloze
    (63005, 20938, 24576),   # самый длинный промпт судьи, плотность 3.01 — минимум замера
    (17040, 4000, 24576),    # плотность 4.26 — МАКСИМУМ замера на 46 промптах, честный вход
])
def test_реальные_честные_вызовы_не_дают_ложной_тревоги(символов, дошло, num_ctx):
    """Верхняя строка — граница, за которой начинались бы ложные тревоги.

    `[замер 31.08.2026, 46 промптов судьи]` плотность 3.01–4.26. Порог обязан оставлять
    над 4.26 запас: иначе честный banking-промпт роняет прогон.
    """
    assert проверить_доставку(символов, дошло, num_ctx) == ""


def test_промпту_хватило_окна_а_ответу_нет():
    """`[случай из данных]` retail__62::t32#0: дошло 24469 при окне 24576 и num_predict 900.
    На ответ осталось 107 токенов, JSON оборвался, строка легла в отчёт как отказ модели."""
    причина = проверить_доставку(символов=73000, дошло=24469, num_ctx=24576, num_predict=900)
    assert "вывод будет оборван" in причина


def test_места_под_ответ_хватает_тревоги_нет():
    assert проверить_доставку(символов=45000, дошло=15000, num_ctx=24576, num_predict=900) == ""


def test_молчание_когда_счётчик_не_сообщён():
    """Нет счётчика — нет и обвинения: судить не о чем."""
    assert проверить_доставку(символов=99999, дошло=0, num_ctx=4096) == ""


def test_граница_потолка_плотности():
    """Ровно на потолке тревоги нет, на волос выше — есть."""
    дошло = 3000
    assert проверить_доставку(int(дошло * СИМВОЛОВ_НА_ТОКЕН_ПОТОЛОК), дошло, 24576) == ""
    assert проверить_доставку(int(дошло * СИМВОЛОВ_НА_ТОКЕН_ПОТОЛОК) + 1, дошло, 24576)


def test_допуск_половины_узкий():
    """Правило про половину окна не должно накрывать соседние значения широкой полосой."""
    половина = 24576 // 2 + 2
    честно = половина + ДОПУСК_ПОЛОВИНЫ + 1
    assert проверить_доставку(int(честно * 3.5), честно, 24576) == ""


