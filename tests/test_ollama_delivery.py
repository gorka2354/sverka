def test_num_ctx_обязателен_и_позиционно_не_передаётся():
    """Забыть окно нельзя: аргумент именованный и без значения по умолчанию."""
    with pytest.raises(TypeError):
        спросить("http://localhost:11434", "модель", "система", "вопрос")  # type: ignore[call-arg]


def test_строгий_режим_поднимает_исключение(monkeypatch):
    """`строго=True` обязано ронять вызов, а не возвращать испорченный ответ."""
    monkeypatch.setattr("sverka.ollama.urllib.request.urlopen", _Перехват(дошло=2050))
    with pytest.raises(ВходОбрезан):
        спросить("http://х", "м", "с" * 1000, "п" * 20038, num_ctx=4096)


def test_нестрогий_режим_возвращает_ответ_с_числом_дошедшего(monkeypatch):
    """`строго=False` — для случая, когда обрезка и есть предмет замера."""
    monkeypatch.setattr("sverka.ollama.urllib.request.urlopen", _Перехват(дошло=2050))
    о = спросить("http://х", "м", "с" * 1000, "п" * 20038, num_ctx=4096, строго=False)
    assert isinstance(о, Ответ) and о.дошло == 2050


def test_пустое_message_не_роняет_разбор(monkeypatch):
    """Тело с `message: null` не должно давать AttributeError вместо внятного ответа."""
    class Пустой(_Перехват):
        def __call__(self, req, *_a, **_kw):
            self.тело = json.loads(req.data.decode("utf-8"))

            @contextlib.contextmanager
            def открыть():
                class Тело:
                    @staticmethod
                    def read():
                        return json.dumps({"message": None,
                                           "prompt_eval_count": 100}).encode("utf-8")
                yield Тело()
            return открыть()

    monkeypatch.setattr("sverka.ollama.urllib.request.urlopen", Пустой())
    о = спросить("http://х", "м", "с", "п", num_ctx=8192)
    assert о.текст == ""
