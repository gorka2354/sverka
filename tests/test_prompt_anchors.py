"""Тесты спасения ранних ходов по значениям из проверяемого ответа.

`[замер 31.08.2026]` Все ложные срабатывания 27B на сэмпле пришлись на усечённые промпты,
а на целых их было ноль. Причин у этого две, и они смешаны: часть фактов мы отрезаем сами
`budget_chars`, часть остаётся в промпте, но модель не находит её на двадцати тысячах
токенов. Отбор по якорям бьёт в обе: он приносит отрезанное и одновременно **сокращает**
промпт, потому что фон вытесняется относящимся к делу.

Предмет тестов — именно это поведение, а не «функция не падает».
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from sverka.judge_prompt import build_prompt  # noqa: E402
from sverka.transcript import parse_response, parse_transcript  # noqa: E402


def транскрипт(ранних: int = 40) -> str:
    """Длинный разговор, где нужный факт лежит в САМОМ раннем ходе."""
    куски = ["⟦SYSTEM⟧", "Политика: возврат по карте, с которой была оплата."]
    куски += ["⟦ASSISTANT⟧", "→ TOOL_CALL get_user: {\"id\": \"u1\"}",
              "← TOOL_RESPONSE get_user: {\"cards\": [{\"last_four\": \"9448\"}]}"]
    for i in range(ранних):
        куски += [f"⟦USER⟧", f"Вопрос номер {i} про доставку и сроки, довольно длинный "
                             f"текст-заполнитель на много символов подряд." * 12]
        куски += [f"⟦ASSISTANT⟧", f"Ответ номер {i}, тоже заполнитель." * 12]
    return "\n".join(куски)


def собрать(**kw):
    tr = parse_transcript(транскрипт(), strict=False)
    turn = parse_response("⟦ASSISTANT⟧\nВозврат уйдёт на карту 9448.", strict=False)
    return build_prompt(tr, turn, **kw)


def контекст(п) -> str:
    """Только блок контекста: в самом проверяемом ответе якорь есть всегда, и искать
    его во всём промпте — значит проверять тавтологию `[промах 31.08.2026]`."""
    i = п.user.find("# Проверяемый ответ агента")
    return п.user[:i] if i > 0 else п.user


def test_без_спасения_ранний_факт_теряется():
    п = собрать(budget_chars=20_000)
    assert п.truncated
    assert "9448" not in контекст(п)


def test_спасение_возвращает_ранний_ход_с_якорем():
    """Главный тест файла: значение, которое судья обязан проверить, обязано быть в промпте."""
    п = собрать(budget_chars=20_000, спасать_якоря=True)
    assert "9448" in контекст(п)


def test_спасение_не_раздувает_промпт():
    """Отбор работает внутри того же бюджета: он вытесняет фон, а не добавляется к нему.
    Иначе лечение усечения само стало бы удлинением контекста."""
    без = собрать(budget_chars=20_000)
    со = собрать(budget_chars=20_000, спасать_якоря=True)
    assert со.approx_tokens <= без.approx_tokens


def test_на_целом_промпте_спасение_ничего_не_меняет():
    """Когда бюджета хватает на весь разговор, поведение обязано совпадать до символа:
    иначе опция меняет замер там, где не должна."""
    tr = parse_transcript("⟦SYSTEM⟧\nПравила.\n⟦USER⟧\nВопрос.", strict=False)
    turn = parse_response("⟦ASSISTANT⟧\nОтвет про карту 9448.", strict=False)
    без = build_prompt(tr, turn, budget_chars=60_000)
    со = build_prompt(tr, turn, budget_chars=60_000, спасать_якоря=True)
    assert без.user == со.user
    assert not без.truncated


def test_разговор_влезающий_целиком_не_становится_усечённым():
    """Регрессия на баг, найденный парным сравнением 31.08.2026.

    Резерв под якоря применялся ВСЕГДА, поэтому разговор, помещавшийся в полный бюджет,
    переставал помещаться в оставшиеся 70% и объявлялся усечённым. В замере это выглядело
    так: контрольная группа целых промптов поехала (полнота 0.533 → 0.400), два примера
    сломались переходом «усечено False → True», и чистота A/B пропала.

    Бюджет здесь подобран так, чтобы разговор влезал целиком, но НЕ влезал в 70% от него, —
    то есть ровно та щель, в которую проваливалась прежняя редакция.
    """
    tr = parse_transcript(транскрипт(ранних=6), strict=False)
    turn = parse_response("⟦ASSISTANT⟧\nВозврат уйдёт на карту 9448.", strict=False)
    без = build_prompt(tr, turn, budget_chars=60_000)
    assert not без.truncated, "проверка бессмысленна: разговор и так не влезает"
    со = build_prompt(tr, turn, budget_chars=60_000, спасать_якоря=True)
    assert not со.truncated
    assert со.user == без.user


def test_ответ_без_якорей_не_ломает_сборку():
    """У короткого ответа извлекаемых значений может не быть вовсе — тогда спасать нечего,
    и промпт должен собраться обычным образом."""
    tr = parse_transcript(транскрипт(), strict=False)
    turn = parse_response("⟦ASSISTANT⟧\nК сожалению, помочь не могу.", strict=False)
    п = build_prompt(tr, turn, budget_chars=20_000, спасать_якоря=True)
    assert п.truncated
    assert п.user
