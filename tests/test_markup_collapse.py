"""Тесты свёртки размеченного корпуса по ходу агента.

Предмет защиты — дефект, найденный 31.08.2026 `[inc-4]`. Майнер `nl_assertions` привязывает
к ходу каждое провалившееся требование отдельно, поэтому один ответ приходил в набор дважды
и трижды (`...::t11#nl11`, `...::t11#nl12`), а у двух ходов метки при этом противоречили
друг другу. Судья видит ход, а не требование: на одинаковом входе он обязан дать одинаковый
вердикт, значит расходящиеся метки делают ошибку неизбежной по построению.
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "scripts"))

from build_markup65 import свернуть_по_ходу  # noqa: E402


def строка(id_: str, label: int, **kw) -> dict:
    return {"id": id_, "label": label, "response": "ответ", "единогласно": True, **kw}


def test_один_ход_остаётся_одной_строкой():
    было = [строка("airline__22::t11#nl11", 0), строка("airline__22::t11#nl12", 0)]
    стало, счёт = свернуть_по_ходу(было)
    assert len(стало) == 1
    assert стало[0]["id"] == "airline__22::t11"
    assert стало[0]["требований"] == 2
    assert счёт == {"поз": 0, "отр": 1}


def test_метка_хода_это_хотя_бы_одно_нарушение():
    """Главный тест файла: ход с расходящимися метками обязан стать положительным.

    Боевая метка отвечает на вопрос «есть ли в ответе галлюцинация», а не «нарушено ли
    конкретное требование», — значит нарушение по любому из требований делает ход
    положительным."""
    было = [строка("airline__14::t20#nl1", 0), строка("airline__14::t20#nl7", 1),
            строка("airline__14::t20#nl9", 0)]
    стало, счёт = свернуть_по_ходу(было)
    assert len(стало) == 1
    assert стало[0]["label"] == 1
    assert счёт == {"поз": 1, "отр": 0}


def test_разные_ходы_не_склеиваются():
    было = [строка("airline__22::t11#nl1", 1), строка("airline__22::t13#nl1", 0),
            строка("retail__5::t2", 1)]
    стало, _ = свернуть_по_ходу(было)
    assert {z["id"] for z in стало} == {"airline__22::t11", "airline__22::t13", "retail__5::t2"}


def test_ход_без_суффикса_требования_проходит_как_есть():
    было = [строка("airline__47::t1", 0)]
    стало, _ = свернуть_по_ходу(было)
    assert стало[0]["id"] == "airline__47::t1"
    assert стало[0]["требований"] == 1


def test_единогласность_теряется_при_разногласии_внутри_хода():
    """Ход, склеенный из карточек, одна из которых размечена большинством 2:1, не может
    считаться единогласным: часть его метки спорна."""
    было = [строка("airline__9::t12#nl1", 1, единогласно=True),
            строка("airline__9::t12#nl2", 0, единогласно=False)]
    стало, _ = свернуть_по_ходу(было)
    assert стало[0]["единогласно"] is False


def test_список_требований_сохраняется():
    """Свёртка не должна прятать, из чего собран ход: иначе потом не проверить,
    какое требование дало метку."""
    было = [строка("airline__22::t11#nl11", 0), строка("airline__22::t11#nl12", 1)]
    стало, _ = свернуть_по_ходу(было)
    assert стало[0]["id_требований"] == ["airline__22::t11#nl11", "airline__22::t11#nl12"]
