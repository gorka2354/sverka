"""Тела ответов инструментов не должны обрываться на пустой строке.

`[баг найден 30.08.2026, исправлен]` Завершитель `\\n\\s*\\n` в `_TOOL_RESP_RE` обрывал тело
ответа на первой пустой строке. На домене banking_knowledge, где ответы инструментов — это
многоабзацные документы базы знаний, до разбора доходило 1 715 символов вместо 69 371:
терялось 98% материала.

Три остальных домена баг не задевал, потому что их ответы — однострочный JSON. Именно
поэтому он и прожил незамеченным: `[замер]` на выданном сэмпле здоровье разбора оставалось
в норме, гейты срабатывали ровно столько же раз, а тесты проходили. Обрыв был тихим.

Тест синтетический намеренно: он не зависит от `data/raw/valid.parquet`, которого нет
в репозитории, и воспроизводит форму дефекта, а не конкретный пример.
"""

from __future__ import annotations

from sverka.transcript import parse_transcript, parse_response

# Ответ инструмента с пустыми строками внутри — форма, на которой ломался разбор.
ДОКУМЕНТ = """Тарифный план «Премиум»

Обслуживание: 0 рублей при остатке от 100 000.

Снятие наличных: до 500 000 в месяц без комиссии.

Условия действуют с 01.01.2026."""


def _транскрипт(тело: str) -> str:
    return (
        "⟦SYSTEM⟧\n"
        "Ты оператор банка.\n"
        "[AVAILABLE TOOLS]\n"
        "get_document(doc_id: str) -> str\n"
        "search_kb(query: str) -> list\n"
        "get_account(account_id: str) -> dict\n"
        "transfer_funds(source: str, target: str, amount: float) -> dict\n"
        "close_account(account_id: str) -> dict\n"
        "get_user_details(user_id: str) -> dict\n"
        "⟦USER⟧\n"
        "Расскажи про премиум.\n"
        "⟦ASSISTANT⟧\n"
        "→ TOOL_CALL get_document: {\"doc_id\": \"doc_42\"}\n"
        f"← TOOL_RESPONSE get_document: {тело}\n"
    )


def тела(текст: str) -> list[str]:
    tr = parse_transcript(текст, strict=False)
    return [т for ход in tr.turns for _, т in ход.tool_responses]


def test_пустая_строка_не_обрывает_тело():
    """Основной случай: многоабзацный документ доходит целиком."""
    найдено = тела(_транскрипт(ДОКУМЕНТ))
    assert len(найдено) == 1, f"ожидался один ответ инструмента, найдено {len(найдено)}"
    assert найдено[0] == ДОКУМЕНТ, (
        f"тело обрезано: {len(найдено[0])} символов вместо {len(ДОКУМЕНТ)}"
    )
    assert "01.01.2026" in найдено[0], "потерян последний абзац — обрыв на пустой строке"


def test_следующий_вызов_по_прежнему_завершает_тело():
    """Обратная сторона: убрав один завершитель, нельзя проглотить соседний вызов."""
    текст = _транскрипт(ДОКУМЕНТ).rstrip("\n") + (
        "\n\n→ TOOL_CALL get_account: {\"account_id\": \"acc_7\"}\n"
        "← TOOL_RESPONSE get_account: {\"balance\": 120000}\n"
    )
    найдено = тела(текст)
    assert len(найдено) == 2, f"ожидалось два ответа, найдено {len(найдено)}"
    assert найдено[0] == ДОКУМЕНТ, "первое тело съело следующий вызов"
    assert найдено[1] == '{"balance": 120000}'
    assert "TOOL_CALL" not in найдено[0], "в тело попал маркер следующего вызова"


def test_граница_хода_завершает_тело():
    """Тело не должно пересекать границу блока: регулярка работает внутри одного хода."""
    текст = _транскрипт(ДОКУМЕНТ).rstrip("\n") + "\n⟦USER⟧\nА комиссия какая?\n"
    tr = parse_transcript(текст, strict=False)
    найдено = [т for ход in tr.turns for _, т in ход.tool_responses]
    assert len(найдено) == 1
    assert "комиссия какая" not in найдено[0], "тело перезахватило следующий ход"
    assert найдено[0] == ДОКУМЕНТ


def test_проверяемый_ответ_разбирается_так_же():
    """`parse_response` использует тот же разбор — дефект был бы и там."""
    ход = parse_response(
        "→ TOOL_CALL get_document: {\"doc_id\": \"doc_1\"}\n"
        f"← TOOL_RESPONSE get_document: {ДОКУМЕНТ}\n",
        strict=False,
    )
    тела_хода = [т for _, т in ход.tool_responses]
    assert тела_хода == [ДОКУМЕНТ]
