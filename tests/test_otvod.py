"""Тесты предиката отвода — на настоящих метках организаторов, а не на выдуманных строках.

Смысл: отвод снимает метку 1, то есть каждое его ложное срабатывание — это пропущенная
галлюцинация. Оба настоящих положительных текстовой страты из `valid.parquet` обязаны
НЕ отводиться, и оба узнаются одним и тем же условием — маркером заявленной невозможности.
Если рефактор ослабит лексикон, эти два теста покраснеют раньше, чем это заметит сабмит.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from sverka.otvod import ОТКАЗ, отвод, тело

DATA = Path(__file__).resolve().parents[1] / "data" / "raw" / "valid.parquet"


def test_маркер_хода_снимается():
    assert тело("⟦ASSISTANT · ход 7⟧\nТекст ответа") == "Текст ответа"


@pytest.mark.parametrize("пусто", ["", "   ", "\n\n", "⟦ASSISTANT · ход 3⟧"])
def test_пустое_тело_не_отводится(пусто):
    """Регрессия на дефект, который стоил бы невозвратного слота `[ревью 31.08.2026]`.

    Переименованная или пустая колонка `response` без этой проверки давала отвод на КАЖДОЙ
    строке — метку 0 везде и F1 = 0.000, притом тихо: исключения нет, watchdog не срабатывает,
    прогон завершается успешно и перезаписывает заранее выписанный пол.
    """
    assert not отвод(пусто).отвести


def test_вызов_инструмента_запрещает_отвод():
    о = отвод("⟦ASSISTANT · ход 3⟧\n\t→ TOOL_CALL book_reservation: {}")
    assert not о.отвести and "вызов" in о.причина


def test_число_запрещает_отвод():
    о = отвод("Ваш возврат составит 1450 рублей.")
    assert not о.отвести and "единиц" in о.причина


def test_пустой_вежливый_ответ_отводится():
    """Ровно тот случай, ради которого конструкция и строится: сказать нечего, соврать негде."""
    о = отвод("Конечно, я помогу вам с этим. Уточните, пожалуйста, что именно вас интересует?")
    assert о.отвести


@pytest.mark.parametrize("фраза", [
    "я не смогу исправить это самостоятельно",
    "выбор конкретных мест не предусмотрен моими инструментами",
    "К сожалению, это невозможно",
    "Переведу вас на оператора",
    "I cannot process this request",
    "I'm unable to modify this reservation",
    "You are not eligible for a refund",
    "Let me transfer you to a human agent",
])
def test_маркеры_невозможности_узнаются(фраза):
    assert ОТКАЗ.search(фраза), f"лексикон не узнал: {фраза}"


@pytest.mark.parametrize("фраза", [
    "Я обновила вашу бронь, всё готово.",
    "Спасибо за ожидание, проверяю данные.",
    "Хорошо, оформляю замену товара прямо сейчас.",
])
def test_обычные_ответы_не_принимаются_за_отказ(фраза):
    assert not ОТКАЗ.search(фраза), f"ложное срабатывание лексикона: {фраза}"


@pytest.mark.skipif(not DATA.exists(), reason="нет data/raw/valid.parquet")
def test_настоящие_положительные_текстовой_страты_не_отводятся():
    """Главный тест файла. Два примера — мало для статистики, но это ЕДИНСТВЕННЫЕ
    положительные текстовой страты с меткой организаторов, какие у нас есть."""
    import pandas as pd

    d = pd.read_parquet(DATA)
    поз = [r for _, r in d.iterrows()
           if r["label"] == 1 and "TOOL_CALL" not in str(r["response"])]
    assert len(поз) == 2, "состав valid.parquet изменился — пересмотреть тест"
    for r in поз:
        о = отвод(str(r["response"]))
        assert not о.отвести, f"{r['id']} отведён, а это настоящая галлюцинация: {о.причина}"


@pytest.mark.skipif(not DATA.exists(), reason="нет data/raw/valid.parquet")
def test_доля_отвода_на_отрицательных_записана():
    """r0 — половина решающего отношения r1/r0. Цифра фиксируется тестом, чтобы её сдвиг
    от правки лексикона был виден сразу, а не всплыл при подсчёте проекции."""
    import pandas as pd

    d = pd.read_parquet(DATA)
    отр = [r for _, r in d.iterrows()
           if r["label"] == 0 and "TOOL_CALL" not in str(r["response"])]
    доля = sum(1 for r in отр if отвод(str(r["response"])).отвести) / len(отр)
    assert 0.30 <= доля <= 0.80, f"r0 на valid уехала до {доля:.3f} — лексикон изменился"
