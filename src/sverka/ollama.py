"""Единственная точка обращения к ollama — с обязательным окном и проверкой доставки.

Модуль появился после `[замер 31.08.2026]`, который отозвал четыре вывода разом.

Вызов к ollama был продублирован в пяти скриптах, и в двух из них `num_ctx` не задавался
вовсе. Без него ollama берёт `OLLAMA_CONTEXT_LENGTH` (на рабочей машине 4096) и делит его
между параллельными слотами. Промпт на 21 038 символов прошёл при этом как
`prompt_eval_count` = 2050 — модель прочитала хвост и не увидела начала. Ошибка **тихая**:
ответ приходит валидный по форме, схема соблюдена, время правдоподобное. Отличить его от
честного «не нашёл» нельзя ничем, кроме счётчика прочитанных токенов.

Цена этой тихой ошибки — четыре записанных вывода, каждый из которых оказался измерением
обрезки, а не модели:

- судья на всём контексте `[полнота 0.224, проекция F1 0.32]` — на деле AUC 0.427 против
  0.731 после починки, то есть измеренный судья был хуже случайного;
- «модель находит дефект, но прощает» `[AUC 0.505]` — она его не видела;
- «пятиступенчатая шкала мертва, ни одного D и E» — D и E появились сразу, 4 и 3 на 46;
- «слепое заполнение пропуска даёт 0.400» — 0.560 на том же наборе, парный подъём +17/−3.

Отсюда два правила, встроенные в код, а не оставленные на внимательность:

1. `num_ctx` — обязательный именованный аргумент без значения по умолчанию. Забыть его
   нельзя: вызов не соберётся.
2. Каждый ответ проходит `проверить_доставку`. При подозрении на обрезку поднимается
   `ВходОбрезан`, потому что замер на обрезанном входе хуже отсутствующего замера —
   он выглядит как результат.
"""

from __future__ import annotations

import json
import time
import urllib.request
from dataclasses import dataclass

# ── Форма обрезки, установленная замером, а не предположением ────────────────────────────
# `[замер 31.08.2026, девять точек]` При переполнении окна ollama читает РОВНО `num_ctx//2 + 2`
# токена, независимо от величины переполнения: 4096 → 2050, 8192 → 4098 (и при 36 тыс., и при
# 46 тыс. символов), 16384 → 8194, 20480 → 10242, 24576 → 12290. Это самый диагностичный
# признак, какой у нас есть, и основную нагрузку несёт он.
ДОПУСК_ПОЛОВИНЫ = 4

# Плотность — вторая линия, на случай другой версии сервера или другого числа слотов, где
# форма обрезки окажется иной. `[замер, 46 реальных промптов судьи, символы против
# фактического prompt_eval_count]` символов на токен: от 3.01 до 4.26, медиана 3.81, p90 4.11.
# Обрезка вдвое удваивает наблюдаемую плотность, то есть даёт 6.0 и выше. Пять — середина
# зазора между 4.26 и 6.0: запас 17% от честного максимума и столько же до самой мягкой
# обрезки. Прежнее значение 7 было НАЗНАЧЕНО, а не выведено, и пропускало ровно ту обрезку,
# от которой защищало: при плотности 3.0 половинное чтение даёт 6.0, что ниже семи.
СИМВОЛОВ_НА_ТОКЕН_ПОТОЛОК = 5.0


class ВходОбрезан(RuntimeError):
    """Модель прочитала не весь промпт. Результат такого вызова недействителен."""


@dataclass(frozen=True)
class Ответ:
    текст: str
    секунд: float
    дошло: int          # prompt_eval_count — сколько токенов промпта модель реально прочитала
    выдано: int         # eval_count
    причина_конца: str  # done_reason: "stop" — договорил, "length" — упёрся в num_predict

    @property
    def вывод_оборван(self) -> bool:
        """Ответ упёрся в `num_predict`. Для схемного вывода это порванный JSON, который
        разборщик молча отдаст как «модель не ответила»."""
        return self.причина_конца == "length"


def проверить_доставку(символов: int, дошло: int, num_ctx: int, num_predict: int = 0) -> str:
    """Причина, по которой вызов считается недействительным, или пустая строка.

    Отделена от запроса, чтобы проверяться тестами без сети: правило, которое некому
    проверить, — это комментарий, а не правило.
    """
    if дошло <= 0:
        return ""  # сервер не сообщил счётчик — судить не о чем, молчим
    if abs(дошло - (num_ctx // 2 + 2)) <= ДОПУСК_ПОЛОВИНЫ:
        return (f"прочитано {дошло} токенов при окне {num_ctx} — это ровно половина окна, "
                f"характерная форма обрезки ollama при переполнении")
    if символов > дошло * СИМВОЛОВ_НА_ТОКЕН_ПОТОЛОК:
        return (f"прочитано {дошло} токенов на {символов} символов — это "
                f"{символов / дошло:.1f} симв/токен при потолке "
                f"{СИМВОЛОВ_НА_ТОКЕН_ПОТОЛОК}, значит прочитана лишь часть")
    if num_predict and дошло + num_predict > num_ctx:
        # Промпт поместился, а ответу места не осталось. `[случай из данных]` строка
        # retail__62::t32#0: дошло 24469 при окне 24576 и num_predict 900 — ответу оставалось
        # 107 токенов, JSON оборвался, и строка легла в отчёт как «модель не ответила».
        return (f"промпт занял {дошло} из {num_ctx} токенов, на ответ остаётся "
                f"{num_ctx - дошло} при запрошенных {num_predict} — вывод будет оборван")
    return ""


def спросить(host: str, model: str, system: str, user: str, *,
             num_ctx: int,
             формат: dict | None = None,
             num_predict: int = 900,
             температура: float = 0.0,
             думать: bool | None = None,
             keep_alive: str | None = None,
             доп_опции: dict | None = None,
             timeout: int = 600,
             строго: bool = True) -> Ответ:
    """Один запрос к ollama.

    `думать`: None — поле `think` не кладётся вовсе; False — кладётся `think: false`.
    Разница измерена и не косметическая `[замер 30.08.2026]`: на qwen3.5 без выключения
    ответ приходит пустым, на gpt-oss:20b — пустым ИМЕННО с выключением. Универсального
    значения нет, поэтому это аргумент, а не константа.

    `строго=False` возвращает ответ вместе с обрезкой вместо исключения — нужно ровно
    в одном случае: когда обрезка и есть предмет замера.

    `доп_опции` вливаются в `options` ПОСЛЕ обязательных, но перезаписать `num_ctx` не
    могут: окно — предмет защиты этого модуля, и подменять его сбоку значит вернуть ту
    самую аварию. Нужны для `num_gpu`, когда модель больше видеопамяти и раскладку слоёв
    надо задать руками, чтобы машина осталась рабочей во время прогона.
    """
    опции: dict = {"temperature": температура, "num_predict": num_predict,
                   "num_ctx": num_ctx}
    if доп_опции:
        опции.update({k: v for k, v in доп_опции.items() if k != "num_ctx"})
    тело: dict = {
        "model": model,
        "messages": [{"role": "system", "content": system},
                     {"role": "user", "content": user}],
        "stream": False,
        "options": опции,
    }
    if формат is not None:
        тело["format"] = формат
    if думать is not None:
        тело["think"] = думать
    if keep_alive is not None:
        тело["keep_alive"] = keep_alive

    req = urllib.request.Request(f"{host}/api/chat",
                                 data=json.dumps(тело).encode("utf-8"),
                                 headers={"Content-Type": "application/json"})
    t0 = time.time()
    with urllib.request.urlopen(req, timeout=timeout) as r:
        о = json.loads(r.read().decode("utf-8"))
    сек = time.time() - t0

    # Строки от модели чистятся на границе: обломок суррогатной пары роняет запись в utf-8
    # и однажды стоил прогона на 24 примерах.
    текст = ((о.get("message") or {}).get("content", "") or "")
    текст = текст.encode("utf-8", "surrogatepass").decode("utf-8", "replace")
    дошло = int(о.get("prompt_eval_count") or 0)

    причина = проверить_доставку(len(system) + len(user), дошло, num_ctx, num_predict)
    if причина and строго:
        raise ВходОбрезан(f"{причина}. Замер на таком ответе недействителен: "
                          f"поднимите num_ctx или укоротите промпт.")
    return Ответ(текст=текст, секунд=сек, дошло=дошло,
                 выдано=int(о.get("eval_count") or 0),
                 причина_конца=str(о.get("done_reason") or ""))


def выгрузить(host: str, model: str, timeout: int = 60) -> None:
    """Снять модель с карты. Нужно после серии прогонов: при `OLLAMA_KEEP_ALIVE=-1`
    веса висят в видеопамяти бесконечно и мешают работать за машиной."""
    тело = json.dumps({"model": model, "messages": [], "keep_alive": 0}).encode("utf-8")
    req = urllib.request.Request(f"{host}/api/chat", data=тело,
                                 headers={"Content-Type": "application/json"})
    with urllib.request.urlopen(req, timeout=timeout):
        pass
