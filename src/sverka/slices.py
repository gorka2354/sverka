"""Срез контекста под одну проверяемую единицу: где искать ответ на вопрос о ней.

Второй слой разложения. Задача узкая: из контекста на тридцать тысяч символов отобрать
несколько кусков, в которых с наибольшей вероятностью лежит значение проверяемой единицы —
и сделать это **вслепую**, не подглядывая в само значение.

⚠️ **Слепота обязательна, и это не осторожность, а условие осмысленности замера.** Если
отбирать куски по вхождению искомого значения, то «значение нашлось в срезе» станет
тавтологией: мы отберём ровно те куски, где оно есть, и получим единицу вместо измерения.
`[у нас уже три замкнутых круга подряд: гейты размечали корпус и на нём же проверялись;
синтетика подменяла ровно то, что искало правило; шаблоны обещаний несли подставной
идентификатор]`. Поэтому в `_якоря` стоит строка, вычитающая значение из набора якорей,
и снимать её нельзя ни при каких обстоятельствах.

Оценка кусков — пересечение по словам с фразой употребления и предыдущей фразой. Простое
совпадение слов, без эмбеддингов.

**Про размер среза.** `[замер 30.08.2026, RU, 53 единицы, у которых значение есть в полном
контексте]` Доля донесённых верных ответов сильно зависит от щедрости отбора:

| k | размер куска | донесено | медиана среза |
|---|---|---|---|
| 6 | 1200 | 0.755 | 4 670 симв |
| 12 | 1200 | 0.868 | 7 654 |
| 6 | 2500 | 0.774 | 4 912 |
| **20** | **2500** | **0.962** | **13 381 симв ≈ 4 050 ток** |

Умолчания взяты из последней строки. Скупой отбор — шесть кусков по 1200 символов, то есть
4.7 тысячи символов из тридцати тысяч контекста — терял четверть верных ответов, и гейт
на качество модели упирался бы в чанкер, а не в модель. Четыре тысячи токенов среза всё ещё
втрое меньше монолита на тринадцать тысяч, на котором судья показал AUC около 0.5.

**0.962 — потолок для любой конструкции на срезах**: выше не поднимется даже безупречная
модель. Гейт на качество модели обязан стоять НИЖЕ этого числа.
"""

from __future__ import annotations

import re
from dataclasses import dataclass

from sverka.judge_prompt import _нормчисло
from sverka.units import Единица, есть_в_тексте

# Куски режутся по естественным границам транскрипта, а не по длине: ответ инструмента,
# раздел политики, ход разговора. Внутри — по длине, чтобы один документ базы знаний
# на семьдесят тысяч символов не съел весь срез.
_ОТВЕТ_ИНСТРУМЕНТА = re.compile(r"[←<]\s*TOOL_RESPONSE\s+([A-Za-z0-9_.\-]+)\s*:?", re.M)
_ХОД = re.compile(r"⟦([^⟧]{0,120})⟧")
_ЗАГОЛОВОК = re.compile(r"^#{1,3}\s+.+$", re.M)

_СЛОВО = re.compile(r"[\w]{3,}", re.U)
_СТОП = {
    "the", "and", "for", "you", "your", "with", "that", "this", "have", "has", "was", "are",
    "not", "can", "will", "from", "все", "для", "что", "как", "это", "или", "быть", "если",
    "так", "его", "её", "их", "вам", "вас", "нас", "при", "над", "под", "про", "уже", "ещё",
}


@dataclass(frozen=True)
class Срез:
    куски: tuple[str, ...]
    якорей: int
    символов: int

    @property
    def пуст(self) -> bool:
        return not self.куски

    def текст(self) -> str:
        return "\n\n---\n\n".join(self.куски)


def _слова(текст: str) -> set[str]:
    return {w.lower() for w in _СЛОВО.findall(текст)} - _СТОП


def _якоря(единица: Единица) -> set[str]:
    """Слова для поиска — из фразы употребления И предыдущей фразы, БЕЗ самого значения.

    `[замер]` Одна только фраза оставляла 23.6% единиц вовсе без якорей; с предыдущей
    фразой — 7.3%. Русский текст часто выносит существительное в предыдущее предложение.
    """
    a = _слова(единица.фраза) | _слова(единица.предыдущая)
    # ↓ ЭТА СТРОКА ДЕЛАЕТ ЗАМЕР ОСМЫСЛЕННЫМ. Без неё срез отбирается по искомому значению,
    #   и «значение нашлось в срезе» превращается в тавтологию.
    a -= {единица.значение.lower(), единица.норма, _нормчисло(единица.значение)}
    return {w for w in a if not w.isdigit() or len(w) >= 4}


def нарезать(контекст: str, *, макс_кусок: int = 2500, макс_раздел: int = 3000) -> list[str]:
    """Контекст на куски по границам транскрипта, затем по длине."""
    границы = sorted({0, len(контекст)}
                     | {m.start() for m in _ОТВЕТ_ИНСТРУМЕНТА.finditer(контекст)}
                     | {m.start() for m in _ХОД.finditer(контекст)}
                     | {m.start() for m in _ЗАГОЛОВОК.finditer(контекст)})
    куски: list[str] = []
    for i, нач in enumerate(границы[:-1]):
        блок = контекст[нач:границы[i + 1]].strip()
        if not блок:
            continue
        предел = макс_раздел if блок.startswith("#") else макс_кусок
        for j in range(0, len(блок), предел):
            часть = блок[j:j + предел].strip()
            if len(часть) > 40:
                куски.append(часть)
    return куски


def отобрать(контекст: str, единица: Единица, *, k: int = 20,
             макс_символов: int = 24_000) -> Срез:
    """Слепо отобрать k кусков, наиболее похожих на окрестность единицы.

    Возвращает пустой срез, если якорей не нашлось или ни один кусок не набрал очков.
    Пустой срез — это исход «непроверяемо» с весом ноль, а НЕ улика против агента:
    отсутствие среза говорит о нашем чанкере, а не об ответе.
    """
    якоря = _якоря(единица)
    if not якоря:
        return Срез((), 0, 0)

    оценки: list[tuple[float, int, str]] = []
    for номер, кусок in enumerate(нарезать(контекст)):
        общие = _слова(кусок) & якоря
        if not общие:
            continue
        # Доля покрытых якорей, а не абсолютное число: длинный кусок иначе выигрывает
        # у короткого просто за счёт словаря.
        оценки.append((len(общие) / len(якоря), -номер, кусок))

    оценки.sort(reverse=True)
    выбранные: list[str] = []
    всего = 0
    for _, _, кусок in оценки[:k]:
        if всего + len(кусок) > макс_символов:
            break
        выбранные.append(кусок)
        всего += len(кусок)
    return Срез(tuple(выбранные), len(якоря), всего)


def потолок(контекст: str, единица: Единица, *, k: int = 20) -> str:
    """Знаменатель для гейтов: где вообще может лежать верный ответ.

    - `нет_якорей`  — вопрос не построить, единица выпадает из замера;
    - `нет_в_контексте` — значения нет и в полном контексте (агент его вычислил или выдумал);
    - `нет_в_срезе` — значение есть в контексте, но чанкер его не донёс: потолок для модели;
    - `в_срезе` — верный ответ доступен, и только здесь модель можно спрашивать честно.
    """
    срез = отобрать(контекст, единица, k=k)
    if not срез.якорей:
        return "нет_якорей"
    if not есть_в_тексте(единица, контекст):
        return "нет_в_контексте"
    return "в_срезе" if есть_в_тексте(единица, срез.текст()) else "нет_в_срезе"
