# Числа. Две альтернативы, а не один жадный класс символов: жадный склеивал перечисления
# вроде «26, 27» в одно число `[замер]`. Первая — разряды через пробел (1 185, 1 185.50),
# вторая — обычное число с десятичной частью. Запятая принимается только как разделитель
# разрядов или дробной части, то есть непосредственно перед цифрами, без пробела.
_ЧИСЛО_RE = re.compile(
    r"\d{1,3}(?:[   ]\d{3})+(?:[.,]\d+)?"
    r"|\d+(?:,\d{3})+(?:\.\d+)?"
    r"|\d+(?:[.,]\d+)?"
)
_ИДЕНТ_RE = re.compile(r"\b(?=[A-Za-z]*\d)(?=\d*[A-Za-z])[A-Za-z0-9][A-Za-z0-9_\-]{2,}\b")


def _нормчисло(s: str) -> str:
    """Свести написание числа к сравнимому виду: 1 185, 1,185, 1185.00 → 1185.

    Сравнение идёт по нормализованной форме, потому что одно и то же число в контексте и
    в ответе почти никогда не написано одинаково: контекст выдаёт JSON от инструментов
    (`1185`), а агент пишет по-русски (`1 185 долларов`). Без нормализации индекс помечал бы
    «не встречается» почти всё, и указание, куда смотреть, превратилось бы в шум.
    """
    ц = re.sub(r"[\s  ]", "", s)
    ц = re.sub(r"[^\d.,]", "", ц)
    # Запятая перед ровно тремя цифрами — разделитель разрядов, её убираем. Остальные
    # запятые десятичные и становятся точкой.
    ц = re.sub(r",(?=\d{3}(?!\d))", "", ц)
    ц = ц.replace(",", ".")
    if ц.count(".") > 1:
        ц = ц.replace(".", "", ц.count(".") - 1)  # оставить только последнюю точку
    if "." in ц:
        ц = ц.rstrip("0").rstrip(".")
    ц = ц.lstrip("0")
    if ц.startswith("."):
        ц = "0" + ц
    return ц or "0"


