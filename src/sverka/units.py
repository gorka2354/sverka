"""Проверяемые единицы: что именно в ответе агента можно сверить с контекстом буквально.

Это первый слой разложения задачи. `[замер 30.08.2026]` Судья на 9B, читающий ответ против
тринадцати тысяч токенов контекста, показал AUC около 0.5 — то есть не отличает испорченный
ответ от чистого вовсе. При этом он **точно называет** расхождение, когда ему указали, куда
смотреть. Отсюда разделение: поиск делаем детерминированно, модели оставляем узкий вопрос
по короткому срезу.

Единица — это одно значение из ответа плюс контекст его употребления: фраза, в которой оно
стоит, и фраза перед ней. Предыдущая фраза нужна не для красоты: `[замер]` без неё доля
единиц, для которых не находится ни одного якоря поиска, была 0.236, с ней — 0.073. Русский
текст часто выносит существительное в предыдущее предложение («Стоимость билета. Она
составит 1 185 рублей»), и по одной фразе искать нечего.

⚠️ Псевдоидентификаторы отсеиваются отдельным списком. `5G`, `2ГБ`, `1st`, `100Mbps` попадают
под общее правило «токен из букв и цифр», но идентификаторами не являются: сверять их
с контекстом бессмысленно, а шума они дают много — особенно в домене telecom.
"""

from __future__ import annotations

import re
from dataclasses import dataclass

from sverka.judge_prompt import _ЧИСЛО_RE, _ИДЕНТ_RE, _нормчисло

# Разбиение на фразы. Точка с последующим пробелом и заглавной, перевод строки, маркеры
# списка. Намеренно грубое: нам нужна окрестность значения, а не лингвистически верное
# предложение.
_ФРАЗА_RE = re.compile(r"(?<=[.!?…])\s+(?=[А-ЯA-Z«\"'\d])|\n+|(?<=\S)\s+(?=[-•*]\s)")

# Служебный маркер хода в начале ответа: `⟦ASSISTANT · ход 10⟧`. Числа внутри него — это
# номер хода, а не утверждение агента. `[инцидент 30.08.2026]` порча номера хода однажды
# уже выдавалась за выдуманное число.
_МАРКЕР_RE = re.compile(r"^\s*⟦[^⟧]*⟧\s*")

# Числа внутри дат и времени. `[инцидент 30.08.2026]` Первая версия извлекала «26», «27»,
# «28» из фразы «даты 26, 27 и 28 мая» и «13» из «13:00». Вопрос «что стоит на месте
# пропуска в „даты (26, 27 и ▮▮▮ мая)"» не имеет однозначного ответа, и модель честно
# отвечала «2024-05-27» там, где мы ждали «27», — а замер считал это провалом модели.
_ДАТА_ВРЕМЯ_RE = re.compile(
    r"\d{4}-\d{2}-\d{2}|\d{1,2}[./]\d{1,2}[./]\d{2,4}|\d{1,2}:\d{2}"
    r"|\d{1,2}\s+(?:янв|фев|мар|апр|ма[йя]|июн|июл|авг|сен|окт|ноя|дек"
    r"|jan|feb|mar|apr|may|jun|jul|aug|sep|oct|nov|dec)",
    re.I,
)

# Единицы измерения, порядковые числительные и обозначения поколений связи. Похожи на
# идентификаторы по форме, но сверять их с контекстом нечего.
_ПСЕВДО_RE = re.compile(
    r"^(?:"
    r"\d+(?:st|nd|rd|th)"                       # 1st, 2nd
    r"|\d+(?:[GgGК]|[кkKмMгГ])"                 # 5G, 4к, 10М
    r"|\d+(?:ГБ|МБ|КБ|Мбит|Кбит|GB|MB|KB|Mbps|Kbps|Gbps|kg|км|мм|см)\w*"
    r"|[A-Za-z]{1,2}\d{1,2}"                    # A4, B2 — слишком короткие, чтобы быть номером
    r")$",
    re.I,
)


@dataclass(frozen=True)
class Единица:
    """Одно проверяемое значение из ответа агента."""

    вид: str          # "число" | "идентификатор"
    значение: str     # как написано в ответе
    норма: str        # нормализованное представление для сравнения
    фраза: str        # предложение, в котором стоит значение
    предыдущая: str   # предложение перед ним (может быть пустым)
    начало: int       # позиция в теле ответа
    конец: int

    def замаскировать(self, маска: str = "▮▮▮") -> tuple[str, str]:
        """Фраза и предыдущая с закрытым значением — вход для слепого заполнения пропуска.

        Маскируется и в предыдущей фразе тоже: если значение повторяется, незакрытая копия
        превращает задачу «найди в данных» в задачу «скопируй из вопроса».
        """
        i = self.фраза.find(self.значение)
        ф = (self.фраза[:i] + маска + self.фраза[i + len(self.значение):]) if i >= 0 else self.фраза
        п = self.предыдущая.replace(self.значение, маска)
        return ф, п


def _тело(ответ: str) -> str:
    m = _МАРКЕР_RE.match(ответ)
    return ответ[m.end():] if m else ответ


def _фразы(текст: str) -> list[tuple[int, str]]:
    """Фразы с позициями начала в исходном тексте."""
    выход, поз = [], 0
    for кусок in _ФРАЗА_RE.split(текст):
        if кусок is None:
            continue
        i = текст.find(кусок, поз)
        if i < 0:
            i = поз
        выход.append((i, кусок))
        поз = i + len(кусок)
    return [(i, к) for i, к in выход if к.strip()]


def _внутри_даты(фраза: str, начало: int, конец: int) -> bool:
    return any(m.start() <= начало and конец <= m.end()
               for m in _ДАТА_ВРЕМЯ_RE.finditer(фраза))


def _примыкает_к_букве(фраза: str, начало: int, конец: int) -> bool:
    """Число, приклеенное к буквам, — часть идентификатора, а не самостоятельное значение.

    `[инцидент]` Из `HAT266` извлекалось число `266`, и вопрос о нём не имел смысла:
    идентификатор целиком уже извлечён отдельной единицей.
    """
    слева = фраза[начало - 1] if начало else " "
    справа = фраза[конец] if конец < len(фраза) else " "
    return слева.isalpha() or справа.isalpha()


def извлечь(ответ: str, *, мин_длина_числа: int = 3) -> list[Единица]:
    """Все проверяемые единицы ответа, по порядку появления.

    `мин_длина_числа` = 3 по умолчанию. `[замер 30.08.2026]` Двузначные давали почти сплошной
    шум: дни месяца, часы, количество пассажиров, номера пунктов. Любое двузначное число
    найдётся в любом контексте, а вопрос о нём чаще всего неоднозначен.

    Отдельно отсеиваются числа внутри дат и времени и числа, примыкающие к буквам: первые
    неоднозначны по построению, вторые — обломки идентификаторов, которые уже извлечены
    целиком отдельной единицей.
    """
    тело = _тело(ответ)
    фразы = _фразы(тело)
    единицы: list[Единица] = []
    видели: set[tuple[str, str]] = set()

    for номер, (нач_фразы, фраза) in enumerate(фразы):
        предыдущая = фразы[номер - 1][1] if номер else ""
        for вид, рег in (("число", _ЧИСЛО_RE), ("идентификатор", _ИДЕНТ_RE)):
            for m in рег.finditer(фраза):
                зн = m.group().strip()
                норма = _нормчисло(зн) if вид == "число" else зн.lower()
                if вид == "число":
                    if len(норма.replace(".", "")) < мин_длина_числа:
                        continue
                    if _внутри_даты(фраза, m.start(), m.end()):
                        continue
                    if _примыкает_к_букве(фраза, m.start(), m.end()):
                        continue
                if вид == "идентификатор" and _ПСЕВДО_RE.match(зн):
                    continue
                ключ = (вид, норма)
                if ключ in видели:
                    continue
                видели.add(ключ)
                единицы.append(Единица(
                    вид=вид, значение=зн, норма=норма,
                    фраза=фраза.strip(), предыдущая=предыдущая.strip(),
                    начало=нач_фразы + m.start(), конец=нач_фразы + m.end(),
                ))
    return единицы


def есть_в_тексте(единица: Единица, текст: str) -> bool:
    """Встречается ли значение единицы в тексте — с учётом написания.

    Числа сравниваются по нормализованной форме: контекст выдаёт JSON от инструментов
    (`1185`), а агент пишет по-русски (`1 185 рублей`), и буквальное сравнение помечало бы
    «нет» почти всегда.
    """
    if единица.вид == "число":
        return единица.норма in {_нормчисло(m.group()) for m in _ЧИСЛО_RE.finditer(текст)}
    return единица.норма in текст.lower()
