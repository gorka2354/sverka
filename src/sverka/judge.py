"""Разбор ответа судьи и превращение его в скор.

Скор непрерывный, а не бинарный, и это решение по замеру: порог придётся выбирать
аналитически. `[замер: сабмиты 30.08.2026]` В текстовой страте — той, где лежат 96 из 130
галлюцинаций, — у нас **ноль размеченных положительных примеров**: на выданном сэмпле их
два, а в корпусе τ² все 4924 положительных имеют вызов инструмента, то есть лежат в чужой
страте. Подгонять порог не на чем, значит он должен выводиться из формы распределения
и известной доли положительных π = 0.241, а не подбираться.

Два способа получить скор, оба здесь:

- `score_from_grade` — по одной букве. Годится, когда движок не отдаёт распределение
  (ollama на мини-ПК). Скор принимает пять значений, разрешение грубое;
- `score_from_distribution` — матожидание по распределению вероятностей на принудительном
  токене оценки. Требует движка с logprobs (vLLM). Скор непрерывный, порог двигается плавно.

Оба опираются на один и тот же приор `GRADE_VALUES` из `judge_prompt`, поэтому переход
между ними не сдвигает шкалу.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass

from sverka.judge_prompt import GRADE_VALUES

# Разбор трёх строк. Намеренно терпимее грамматики: грамматика гарантирует формат только
# там, где движок её поддерживает, а на движке без неё разбор всё равно должен работать.
_FINDING_RE = re.compile(r"^\s*FINDING\s*:\s*(.+?)\s*$", re.M | re.I)
_EVIDENCE_RE = re.compile(r"^\s*EVIDENCE\s*:\s*(.+?)\s*$", re.M | re.I)
_GRADE_RE = re.compile(r"^\s*GRADE\s*:\s*\**\s*([ABCDE])\b", re.M | re.I)

# Скор, когда разобрать оценку не удалось. Ноль, а не середина: `[E1b]` разрешение судье
# воздержаться обрушило полноту 0.733 → 0.200, то есть неопределённость дороже пропуска.
# Доля таких случаев обязана логироваться — на движке с грамматикой она должна быть нулевой,
# и её рост означает поломку, а не трудный пример.
FALLBACK_SCORE = 0.0


# Таблица вывода скора из того, что модель СООБЩИЛА, а не из того, какую оценку она себе
# поставила. `[замер 30.08.2026, санити-прогон v2]` Судья находил настоящие дефекты и тут же
# прощал их: «список рейсов включает HAT078 и HAT118, которых не было в маршруте» — оценка A;
# «агент запросил дату рождения, которая уже известна» — оценка B. Разрыв средних скоров
# между классами вышел +0.035 при том, что находки были содержательными.
#
# Отсюда разделение труда: модель делает то, что умеет — читает контекст и описывает
# расхождение; агрегирует наш код, где правило видно, воспроизводимо и правится без
# перепрогона. Ключ — (худший статус проверок, влияние на клиента).
_ВЫВОД_СКОРА = {
    ("противоречит", "меняет"):      0.95,
    # `[замер v3]` Пара «противоречит + не меняет» встретилась массово и стоила доли ложных
    # 0.571 в текстовой страте при целевой 0.15. Модель называет противоречием любое
    # несовпадение строки, поэтому её «противоречит» без подтверждения влиянием весит мало.
    ("противоречит", "не меняет"):   0.35,
    ("противоречит", "нечего"):      0.35,
    ("не найдено", "меняет"):        0.80,
    ("не найдено", "не меняет"):     0.20,
    ("не найдено", "нечего"):        0.20,
    # Вычисленное значение — нормальная работа агента, а не дефект. Отдельный статус нужен
    # ровно затем, чтобы посчитанная сумма не попадала в «не найдено» просто потому,
    # что её нет в контексте дословно.
    ("выводится вычислением", "меняет"):    0.45,
    ("выводится вычислением", "не меняет"): 0.05,
    ("выводится вычислением", "нечего"):    0.03,
    ("подтверждено", "меняет"):      0.45,   # нашла что-то мимо проверок и говорит, что важно
    ("подтверждено", "не меняет"):   0.05,
    ("подтверждено", "нечего"):      0.02,
}


def _влияние(impact: str) -> str:
    низ = (impact or "").lower()
    if низ.startswith("меняет"):
        return "меняет"
    if низ.startswith("не меняет"):
        return "не меняет"
    return "нечего"


def _худший_статус(checks) -> str:
    статусы = {str(c.get("status", "")).strip().lower() for c in checks if isinstance(c, dict)}
    # Порядок тяжести. «Выводится вычислением» стоит НИЖЕ «не найдено» намеренно: это
    # нормальная работа агента, а не дефект, и попадать в него должны посчитанные суммы.
    for s in ("противоречит", "не найдено", "выводится вычислением"):
        if s in статусы:
            return s
    return "подтверждено"


def score_derived(checks, impact: str) -> float:
    """Скор из отчёта модели. Оценку, которую модель ставит себе сама, здесь не используем."""
    return _ВЫВОД_СКОРА.get((_худший_статус(checks or []), _влияние(impact)), FALLBACK_SCORE)


@dataclass(frozen=True)
class Вердикт:
    score: float           # основной: выведен нашим кодом из отчёта модели
    grade: str | None
    finding: str
    evidence: str
    parsed: bool
    raw: str = ""
    score_grade: float = 0.0   # альтернативный: по букве, которую поставила модель
    impact: str = ""
    checks: tuple = ()

    @property
    def label(self) -> int:
        raise NotImplementedError("метка ставится порогом снаружи, а не вердиктом")


def score_from_grade(grade: str) -> float:
    return GRADE_VALUES.get(grade.upper(), FALLBACK_SCORE)


def score_from_distribution(dist: dict[str, float]) -> float:
    """Матожидание приора по распределению вероятностей на токене оценки.

    `dist` — вероятности токенов, какими их отдал движок. Токены, не входящие в шкалу,
    отбрасываются, остаток перенормируется: движок может вернуть верхние k токенов, среди
    которых окажется пробел или перевод строки, и их вес не должен утекать в скор.
    """
    веса = {k.strip().upper(): v for k, v in dist.items()}
    веса = {k: v for k, v in веса.items() if k in GRADE_VALUES and v > 0}
    сумма = sum(веса.values())
    if not сумма:
        return FALLBACK_SCORE
    return sum(GRADE_VALUES[k] * v for k, v in веса.items()) / сумма


def _из_json(text: str):
    """Достать три поля из объекта JSON, даже если модель обернула его в текст.

    Основной путь — принудительное декодирование по схеме, и тогда `text` это чистый объект.
    Запасной нужен на движке без форсирования: `[замер]` комплаенс свободного формата 0.74,
    и все отказы приходились на длинные окна, то есть на самый сложный материал.
    """
    начало = text.find("{")
    конец = text.rfind("}")
    if начало < 0 or конец <= начало:
        return None
    try:
        o = json.loads(text[начало:конец + 1])
    except (json.JSONDecodeError, ValueError):
        return None
    if not isinstance(o, dict):
        return None
    g = str(o.get("grade", "")).strip().upper()[:1]
    checks = o.get("checks") if isinstance(o.get("checks"), list) else []
    return (g if g in GRADE_VALUES else None,
            str(o.get("finding", "")), str(o.get("evidence", "")),
            str(o.get("impact", "")), checks)


def parse_verdict(text: str, dist: dict[str, float] | None = None) -> Вердикт:
    """Разобрать ответ судьи. Не бросает исключений: прогон стоит попытки."""
    из_json = _из_json(text or "")
    if из_json is not None:
        grade, finding, evidence, impact, checks = из_json
        по_букве = score_from_distribution(dist) if dist else (
            score_from_grade(grade) if grade else FALLBACK_SCORE)
        # Основной скор выводится из отчёта, а не из самооценки модели: см. _ВЫВОД_СКОРА.
        # Если отчёт неполон (нет ни проверок, ни влияния), падаем обратно на букву.
        основной = score_derived(checks, impact) if (checks or impact) else по_букве
        return Вердикт(score=основной, grade=grade, finding=finding, evidence=evidence,
                       parsed=grade is not None, raw=text or "",
                       score_grade=по_букве, impact=impact, checks=tuple(checks))

    # Запасной разбор построчного формата — на случай движка, который проигнорировал схему.
    g = _GRADE_RE.search(text or "")
    f = _FINDING_RE.search(text or "")
    e = _EVIDENCE_RE.search(text or "")
    grade = g.group(1).upper() if g else None
    if dist:
        score = score_from_distribution(dist)
    elif grade:
        score = score_from_grade(grade)
    else:
        score = FALLBACK_SCORE
    return Вердикт(
        score=score,
        grade=grade,
        finding=f.group(1) if f else "",
        evidence=e.group(1) if e else "",
        parsed=bool(g),
        raw=text or "",
    )


def предсказать_метрики(scores, метки, *, порог: float, pi: float = 0.241):
    """Спроецировать локальные ставки на реальный набор с известной долей положительных.

    Считать F1 прямо на выданном сэмпле нельзя: `[замер §0в]` в нём 50/50 по классам против
    реальных 24/76, и внутри каждой страты пропорция перевёрнута. Но доля срабатываний
    отдельно на положительных (полнота) и отдельно на отрицательных (доля ложных) переносится
    — переносится не она сама, а то, что из неё считается при **реальной** доле π.
    """
    поз = [s for s, m in zip(scores, метки) if m == 1]
    отр = [s for s, m in zip(scores, метки) if m == 0]
    if not поз or not отр:
        return None
    tpr = sum(s >= порог for s in поз) / len(поз)
    fpr = sum(s >= порог for s in отр) / len(отр)
    tp, fp, fn = pi * tpr, (1 - pi) * fpr, pi * (1 - tpr)
    точность = tp / (tp + fp) if tp + fp else 0.0
    f1 = 2 * tp / (2 * tp + fp + fn) if tp else 0.0
    return {
        "порог": порог,
        "полнота": tpr,
        "доля_ложных": fpr,
        "n_положительных": len(поз),
        "n_отрицательных": len(отр),
        "прогноз_точности": точность,
        "прогноз_F1": f1,
    }


def выбрать_порог(scores, метки, *, pi_диапазон=(0.15, 0.35), шаг=0.01):
    """Порог по maximin: лучший худший случай на диапазоне доли положительных.

    Оптимизировать под π = 0.241 нельзя: это доля **публичного** набора, а победителей
    определяет приватный, где она может отличаться. Берётся порог, у которого хуже всего
    получившийся F1 максимален по диапазону π.
    """
    кандидаты = sorted({round(s, 3) for s in scores} | {0.5})
    лучшее = None
    for порог in кандидаты:
        худший = min(
            (предсказать_метрики(scores, метки, порог=порог, pi=pi) or {}).get("прогноз_F1", 0.0)
            for pi in [pi_диапазон[0] + i * шаг
                       for i in range(int((pi_диапазон[1] - pi_диапазон[0]) / шаг) + 1)]
        )
        if лучшее is None or худший > лучшее[1]:
            лучшее = (порог, худший)
    return лучшее
