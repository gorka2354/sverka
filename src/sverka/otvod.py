"""Отвод — предикат «этот ответ заведомо безопасен, метку 1 можно снять».

Конструкция перевёрнута относительно всего, что делалось раньше, и вот почему.
`[замеры 30–31.08.2026]` Три линии поиска галлюцинаций опровергнуты подряд: гейты
(покрытие 5.4%, точность 0.412), судья-оценщик (взвешенная проекция F1 = 0.123 при поле
0.393, то есть втрое хуже бездействия) и извлекающая сверка (AUC 0.529 при записанном
до прогона гейте 0.6). При этом файл из одних единиц даёт F1 = 0.393 без единой строки
логики.

Отсюда постановка: не «найти виновных», а **оправдать невиновных**. Метка 1 стоит по
умолчанию, и низ гарантирован конструкцией — падение, обрезка входа, срабатывание watchdog
дают ровно пол, а не ноль. Снимается метка только там, где ответ заведомо безобиден.

**Критерий выгодности снятия — арифметика F1, а не вкус.** Снимать метку с ведра выгодно
тогда и только тогда, когда доля положительных внутри ведра p < F1/2 = 0.194. При доле
положительных π = 0.258 в текстовой страте это сворачивается в одно неравенство:

    r1 / r0 < 0.692,

где r1 — доля отводимых среди положительных, r0 — среди отрицательных. Измерено на сегодня:
r0 = 0.644 (160 надёжных отрицательных) и 0.714 (21 отрицательный valid); r1 = 0.5 —
но **на двух примерах**, и 80%-интервал Уилсона даёт отношение 0.23–1.17, то есть порог
лежит внутри. Замер r1 на сорока примерах и есть шаг 1 инкремента 3.

**Три условия отвода, каждое со своим основанием:**

1. **Нет вызова инструмента.** Действий агент не совершал, значит нарушить политику
   действием не мог.
2. **Нет извлекаемых единиц.** Ни чисел, ни идентификаторов — нечего выдумать и не с чем
   разойтись. `[замер]` доля таких ответов: 0.644 среди надёжных отрицательных, 0.714
   среди отрицательных valid.
3. **Нет маркера невозможности.** Ложный отказ — единственная категория, которая живёт
   в ответах без чисел, и оба настоящих положительных текстовой страты из `valid.parquet`
   содержат такой маркер: «выбор конкретных мест не предусмотрен моими инструментами»
   (`airline__8::t7`) и «я не смогу исправить это самостоятельно с помощью имеющихся
   инструментов» плюс перевод на оператора (`retail__29::t13`). Без третьего условия
   отвод накрыл бы их обоих.

⚠️ **Лексикон замораживается коммитом ДО замера на пуле.** Он собран по двум настоящим
положительным и по здравому смыслу, а не подобран под выборку — иначе это был бы седьмой
замкнутый круг подряд. Любое расширение после замера обязано проходить через одно число
(падает ли r1/r0), а не через чтение примеров.
"""

from __future__ import annotations

import re
from dataclasses import dataclass

from sverka.units import извлечь

# Маркер хода в отрендеренном ответе: «⟦ASSISTANT · ход 7⟧». Снимается тем же способом,
# что в units.py, иначе предикат считал бы служебную обёртку содержанием ответа.
_МАРКЕР = re.compile(r"^⟦[^⟧]*⟧\s*", re.MULTILINE)

# Заявление о невозможности или передача человеку. Ловит и прямой отказ, и мягкую его форму
# («не предусмотрено моими инструментами»), потому что по рубрике ТЗ ложным отказом считается
# именно объявленная невозможность, а не грубость формулировки.
ОТКАЗ = re.compile(
    r"не\s+смог|не\s+мог|не\s+получ|не\s+удас|не\s+удал|невозможн|не\s+предусмотр"
    r"|не\s+поддержив|не\s+позволя|не\s+имею\s+возможн|нет\s+возможн|не\s+подлеж"
    r"|нельзя|не\s+вправе|не\s+уполномоч|не\s+располагаю"
    r"|перевед[уё]|перевест[иь]|оператор|специалист|живому\s+агенту|коллег"
    r"|cannot|can't|can not|unable\s+to|not\s+able|do\s+not\s+have\s+access"
    r"|don't\s+have\s+access|not\s+eligible|does\s+not\s+qualify|not\s+permitted"
    r"|not\s+authorized|no\s+ability|transfer\s+you|human\s+agent|live\s+agent",
    re.IGNORECASE,
)

# Вызов инструмента в отрендеренном ответе. Оба формата, которые встречались в данных.
ВЫЗОВ = re.compile(r"TOOL_CALL|⟦ASSISTANT_TOOL_CALL", re.IGNORECASE)


@dataclass(frozen=True)
class Решение:
    отвести: bool
    причина: str


def тело(ответ: str) -> str:
    """Текст ответа без служебного маркера хода."""
    return _МАРКЕР.sub("", ответ or "").strip()


def отвод(ответ: str) -> Решение:
    """Можно ли снять метку 1 с этого ответа.

    Возвращает решение и причину отказа от отвода — причина нужна, чтобы разбирать
    промахи по слоям, а не гадать, какое из трёх условий сработало.
    """
    т = тело(ответ)
    # ⚠️ Пустое тело НЕ отводится. `[ревью 31.08.2026]` Без этой проверки переименованная
    # или пустая колонка `response` даёт отвод на КАЖДОЙ строке, то есть метку 0 везде
    # и F1 = 0.000, причём тихо: исключения нет, watchdog не срабатывает, прогон завершается
    # успешно и перезаписывает заранее выписанный пол. Это ровно противоположно несущему
    # обещанию конструкции («низ гарантирован»), и цена — невозвратный слот.
    if not т:
        return Решение(False, "пустое тело ответа — данные не разобраны, отвод запрещён")
    if ВЫЗОВ.search(ответ or ""):
        return Решение(False, "есть вызов инструмента")
    if ОТКАЗ.search(т):
        return Решение(False, "заявлена невозможность или передача человеку")
    единицы = извлечь(т)
    if единицы:
        return Решение(False, f"есть проверяемые единицы: {len(единицы)}")
    return Решение(True, "нет действий, нет утверждений о значениях, нет отказа")
