"""Узкий вопрос к модели: что стоит на месте пропуска по данным среза.

Это третий слой разложения и единственное место, где участвует модель. Постановка выбрана
по измеренному, а не по вкусу.

`[замер 30.08.2026]` Судья, читавший ответ агента против тринадцати тысяч токенов контекста
и выносивший вердикт «есть ли нарушение», показал AUC около 0.5 — то есть не отличал
испорченный ответ от чистого. При этом он **точно называл** расхождение, когда ему
указывали, куда смотреть. Три вывода легли в основу этой постановки:

1. **Модель не ищет по полотну.** Поиск делаем сами: срез строится детерминированно и
   вслепую (`slices.py`), и в нём верный ответ лежит в 96% случаев `[замер]`.
2. **Модель не решает, что важно клиенту.** Ни о какой важности здесь не спрашивают. Вопрос
   чисто извлекающий: какое значение стоит на месте пропуска.
3. **Отчёту модели о себе верить нельзя.** На 156 заведомо чистых ходов она написала
   90 «противоречит» и 222 «не найдено». Поэтому вердикт выводится НЕ из её слов, а из
   проверки её цитаты нашим кодом: цитата обязана дословно найтись в срезе, а значение —
   в цитате. Выдуманная улика отбрасывается механически.

Два ответа объявлены **правильными**, а не отказом: «НЕТ ДАННЫХ», когда в срезе нужного нет,
и «НЕОДНОЗНАЧНО», когда подходящих значений несколько и они разные. `[E1b]` Разрешение
воздержаться от ВЕРДИКТА обрушивало полноту 0.733 → 0.200, но здесь воздержание касается
не вердикта, а факта: сказать «в данных этого нет» — содержательный ответ, и запрещать его
значило бы вынуждать модель выдумывать.
"""

from __future__ import annotations

import re
from dataclasses import dataclass

from sverka.judge_prompt import _нормчисло
from sverka.units import Единица

МАСКА = "▮▮▮"

SYSTEM = """Ты — программа поиска по данным. Тебе дают фрагмент данных и один вопрос по нему.

Ты не оцениваешь, правильно ли поступил кто-либо, и не решаешь, важно ли расхождение.
Ты только находишь в данных то, о чём спрашивают, и выписываешь это дословно.

Правила:
1. Поле «цитата» — фрагмент, скопированный из данных СИМВОЛ В СИМВОЛ. Если в цитате окажется
   то, чего в данных нет, ответ будет отброшен целиком.
2. Если нужного в данных нет — верни значение "НЕТ ДАННЫХ". Это правильный ответ, а не
   неудача.
3. Если подходящих значений несколько и они разные — верни "НЕОДНОЗНАЧНО".
4. Ничего не вычисляй. Если значение нужно было бы получить сложением или вычитанием —
   это "НЕТ ДАННЫХ"."""

SCHEMA = {
    "type": "object",
    "properties": {
        # Цитата первой: модель обязана сначала найти опору и лишь потом назвать значение.
        # При принудительном декодировании порядок ключей задаётся схемой, а не моделью.
        "цитата": {"type": "string", "maxLength": 300},
        "поле": {"type": "string", "maxLength": 60},
        "значение": {"type": "string", "minLength": 1, "maxLength": 60},
    },
    "required": ["цитата", "поле", "значение"],
}


@dataclass(frozen=True)
class Вопрос:
    system: str
    user: str
    единица: Единица
    срез: str


def собрать(единица: Единица, срез_текст: str) -> Вопрос:
    фраза, предыдущая = единица.замаскировать(МАСКА)
    хвост = f'Фраза перед ней: «{предыдущая}»\n' if предыдущая else ""
    user = (
        f"# Данные\n\n{срез_текст}\n\n"
        f"# Вопрос\n\n"
        f"Агент написал клиенту фразу. Одно значение в ней закрыто пропуском {МАСКА}:\n"
        f"«{фраза}»\n"
        f"{хвост}"
        f"\nКакое значение стоит на месте {МАСКА} по данным выше? "
        f"Скопируй его из данных дословно, ничего не вычисляя.\n"
    )
    return Вопрос(system=SYSTEM, user=user, единица=единица, срез=срез_текст)


_ПРОБЕЛЫ = re.compile(r"\s+")


def _сжать(s: str) -> str:
    return _ПРОБЕЛЫ.sub(" ", (s or "")).strip().lower()


def _сравнимы(a: str, b: str, вид: str) -> bool:
    if вид == "число":
        return _нормчисло(a) == _нормчисло(b)
    return _сжать(a) == _сжать(b)


def проверить(ответ: dict, вопрос: Вопрос) -> str:
    """Исход по ответу модели — решает НАШ код, а не её самооценка.

    - `непроверяемо` — цитата не найдена в срезе дословно, или значения нет в цитате,
      или модель сказала «НЕОДНОЗНАЧНО». Улика не подтверждена, вес ноль;
    - `нет_опоры` — модель честно сказала, что в данных этого нет;
    - `подтверждено` — найденное значение совпало с тем, что написал агент;
    - `противоречит` — найденное значение отличается от написанного агентом.
    """
    if not isinstance(ответ, dict):
        return "непроверяемо"
    цитата = _сжать(str(ответ.get("цитата", "")))
    значение = str(ответ.get("значение", "")).strip()
    if not цитата or цитата not in _сжать(вопрос.срез):
        return "непроверяемо"          # улика выдумана — отбрасываем целиком
    if значение.upper() == "НЕТ ДАННЫХ":
        return "нет_опоры"
    if значение.upper() == "НЕОДНОЗНАЧНО":
        return "непроверяемо"
    if _сжать(значение) not in цитата:
        return "непроверяемо"          # значение не подпёрто собственной же цитатой
    return ("подтверждено" if _сравнимы(значение, вопрос.единица.значение, вопрос.единица.вид)
            else "противоречит")
